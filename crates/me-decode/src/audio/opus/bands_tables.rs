//! ## 这两张表是干什么的
//!
//! CELT 给每个频带分配的不是"多少位"，而是**脉冲数 K**（金字塔矢量量化的 L1 范数）。
//! 参考实现预先算好了"每个频带宽度 × 每个 K → 需要的位数"，于是解码时只要二分
//! 就能反过来把 `b`（分到的位数）变成最大的 `K` —— 就是 [`CACHE_BITS`]：
//!
//! - [`CACHE_INDEX`]：`[LM+1][band] → CACHE_BITS` 里的下标。相同（带宽, LM）组合
//!   共用一段，所以表很小。注意参考实现里入口是 `LM+1`（`bits2pulses` 先 `LM++`），
//!   所以本表有 `maxLM+2` 行（多出来的一行给"再拆一次"的递归用，见 `quant_band`）。
//! - [`CACHE_BITS`]：每段是 `[K_max, bits(1), bits(2), …]` —— 第 0 项是**该段最大的 K**
//!   （`bits2pulses` 二分的上界），第 `k` 项是 K=k 时需要的位数减一
//!   （参考实现里 `ptr[j] = tmp[get_pulses(j)]-1`，用 `pulses2bits` 时再加回来）。

