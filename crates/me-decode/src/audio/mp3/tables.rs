//!
//! 这里的每张表都**直接对应标准里的某张表**，不是从别的实现里抄的：
//!
//! | 表 | 出处 |
//! |---|---|
//! | 哈夫曼树（17 棵） | ISO/IEC 11172-3 Table 3-B.7（由参考树表展开成显式节点） |
//! | 比例因子频带宽度 | 标准 Table 3-B.8（长块 22 带 / 短块 13 带 × 3 窗） |
//! | 多相合成窗 D[512] | 标准 Table 3-B.3（只存前 257 项，另一半按镜像关系反射） |
//! | 混叠抑制旋转系数 | 标准 Table 3-B.9 |
//! | 预加重偏置 `pretab` | 标准 Table 3-B.6 |
//! | MPEG-1 比例因子位宽 `slen1/slen2` | 标准 Table 3-B.4 |
//! | LSF（MPEG-2/2.5）比例因子分解尺寸 | ISO/IEC 13818-3 表 B.2 |
//!
//! 生成期自校验（写在开发笔记里，改表时请重跑）：
//!
//! - 每棵哈夫曼树的 **Kraft 和必须恰好为 1**（完备前缀码），且最大码长与标准一致。
//!   抄错一个偏移就会让 Kraft 和偏离 1，或在解码时走进空槽。
//! - 合成窗前 257 项按 `D[512-i] = -D[i]`（i & 63 ≠ 0 取负）反射后，必须与标准
//!   全表逐项吻合 —— 只存一半的前提是这条关系成立。
//! - 每行频带宽度表求和必须恰好 576（长块）或 3×192（短块），否则谱线位置会整体错位。
//!
//! ## 为什么哈夫曼树要展开成显式节点
//!
//! 标准表本身是"码字 → (x, y)"的清单。解码时如果每次都线性查表，最坏要比较几百次。
//! 展开成树之后，每读一位就前进一层，**代价与码长成正比**；而且树是完备前缀码，
//! 读满 `max_code_len` 位必定落到叶子上，不会出现"读到的位串无对应码字"这种
//! 需要额外兜底的分支 —— 这一点让解码循环可以写得非常短。

