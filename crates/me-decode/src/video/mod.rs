//! | `bzero` 合计 | 2.9%（其中 `Plane::clone` **1.3%**、其余是帧缓冲分配）|
//! | **`lr::apply` 的 worker 闭包自身** | **2.9%** —— 其实是 `restore_block`
//!   **被内联**后的胶水（它不在 top-of-stack 表里）|
//! | **`warp::block_warp`** | **2.7% → 本轮清零** |
//!
//! ⚠️ `sample` 的 top-of-stack 表格式是 `<符号> (in <库>) <计数>` —— **计数在行尾**，
//! 用"行首数字"的正则去解析会得到**空表**（这次就踩了一次）。
//!
//! ### 下一批候选（按"收益 ÷ 风险"）
//!
//! | 目标 | 占整帧 | 判断 |
//! |---|---|---|
//! | **`restore_block` 胶水** | **2.9%** | 先看它的逐 4×4 展开里有没有每块重算的东西 |
//! | `vt_forward_1d` 的 i32 路 | 4.6% | 界已算好：`Σ两项 ≤ 2^(7+bd)·2^13` ⇒ 8bit 富余 8 倍、10bit 3 倍 ⇒ 可按位深分派；12bit 仍 i64。改动面大（`vt_*` 全家 + 两个驱动）|
