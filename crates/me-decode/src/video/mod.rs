//! ## 熵层（M3）的验收口径，也要说清楚
//!
//! - `read_symbol` 的正确性靠**两份独立实现对拍**：`entropy.rs` 末尾的固定向量是
//!   拿一份照规范另写的 Python 解码器（`av1_entropy_ref.py`，在
//!   `lerxu-av1-softdecode` 技能目录里）算出来的 ——
//!   同一段确定性数据、同一份 CDF（直接取规范里的真实表），两边必须给出**一样的
//!   符号序列、一样的自适应后 CDF、一样的位位置**。位序/移位/掩码这类"自洽地错"
//!   只有这样才能抓出来。
//! - 真实素材上验的是"核心不变量 + 位记账"：每次读符号后 `SymbolValue < SymbolRange`，
//!   读满一个瓦片后位置指示器正好等于字节数。
//! - **`exit_symbol()` 的硬验收已经过了**：见下面"块级语法（M4b）的验收口径"。
//!
//! ## 块级语法（M4b）的验收口径：**`exit_symbol()` + 「应有消耗位」**
//!
//! `exit_symbol()` 比任何单测都硬 —— 符号数、每个符号用的 CDF / 上下文、位记账里
//! 任何一处错位，读到的位置就不会正好落在编码器写下的那个 `1` + 补零上，而且
//! **不需要参考解码器**。它还能进一步化简成一个**精确整数**：消耗位必须恰好等于
//! 「瓦片里最后一个 `1` 的位置」（推导见
//! [`entropy::required_consumed_bits`]）。
//!
//! 现状：`tools/av1probe/samples/` 里 14 条**真实编码器（libaom，经 Chrome
//! WebCodecs）写出来的**流全部逐位精确吻合（16×16 / 32×32 / 64×64，含残差非零、
//! 残差进 Exp-Golomb 的形态），常驻回归测试
//! `bundled_probe_streams_pass_exit_symbol_exactly`。
//!
//! **这一条判据踩过的坑值得记下来**（2026-09-30，白查了一轮）：
//! `required` 原本是在 `me-cli` 里**就地**扫位算的，扫位顺序写反了 ——
//! 每个字节里后写的赋值覆盖前面的，于是取到的是「末字节**最高位**那侧的 `1`」
//! 而不是整段最后一个 `1`。于是 14 条流被整齐地报成"少读 1~6 位"，
//! 看起来像"残差非零的路径漏读了符号"，还据此展开过一轮"缺的那几个符号是谁"的搜索。
//! 判据改正后**一条都不差**。教训：**绝对判据只能有一份实现**（现在是
//! [`entropy::required_consumed_bits`]，带单测，`tools/av1probe/required_bits.py`
//! 是它的独立 Python 复算），而且"差得整齐"要先去怀疑判据本身。
//!
//! **待复核**：更长的真实素材（B 站 1080p 那批，36845 个瓦片组）需要
//! `AV1_REAL_FILE`；本轮沙箱里没有这份素材，所以模块里旧文档提到的
//! "keyframe 多读 17936 位（8.97%）"**没有复跑**，无法确认它现在是否已经随着
//! 其它修复（Golomb 长度码极性等）一起消失。要下结论就设好 `AV1_REAL_FILE` 跑
//! `real_av1_file_blocks_consume_the_entropy_stream`。已知与它无关的差异只有
//! `save_cdfs` / `load_cdfs`（帧间帧的前提；keyframe 用不到）。
//!
//! ## 真实素材第 34 帧的越界 —— 2026-10-01 定位并修复（`reset_block` 的色度清范围）
//!
//! 把 B 站 ASMR 1080p 那份素材当**整条轨**跑（而不是 `--count=8` 只解前 8 帧）曾会发现：
//!
//! ```sh
//! zuvrust decode "<ASMR>" --count=34 --out=/tmp/x --json   # 修复前 ✗ 越界，修复后 ✓
//! zuvrust decode "<ASMR>" --count=8  --out=/tmp/x --json   # ✓ ok:true
//! ```
//!
//! **`--count` 必须写等号形式**（`opt()` 只认 `--count=N`；写成 `--count 34` 会被静默忽略、
//! 变成整轨跑）—— 2026-09-30 那句"`--count=8` → ok"就是被这个限制挡住了，所以只验到
//! 解码顺序前 7 帧逐符号一致，**第 8 帧往后从未验过**。
//!
//! **根因**（`coeff.rs::CoeffContexts::reset_block`）：规范 §5.11.4 尾部的
//! `reset_block_context( bw4, bh4 )` 里，色度的清范围是
//! `i = MiCol >> subX .. ( MiCol + bw4 ) >> subX`（**下界取整、上界取整**），
//! 旧实现写成"`bw4` 是奇数就一格都不清"。于是 `bw4 = 1`、`MiCol = 311` 的 4×4 跳过块
//! 本该清 `[155,156)` 一格却清了 0 格 ⇒ 列 155 上残留上一个变换块写下的 `level`
//! ⇒ 该列的 `txb_skip` 选到错误上下文（`skip_ctx` 7 → 8）⇒ CDF 选错 ⇒ 从那里起整条
//! 算术流错位（症状：**前 8841 个变换块逐符号全对，第 8842 个符号值相同但 CDF 不同**）。
//!
//! **怎么定位的**（这套流程可复用，见 `lerxu-av1-softdecode` 技能 §4l）：
//!
//! 1. `AV1_TRACE_SB=1` 逐超块记账 + 与同 GOP 第一个 alt-ref 帧按位比例比对 ⇒
//!    分叉在超块索引 36/37（`mi_r=64`、`c=192/224`）之后，不在帧头（帧头错第一个超块就炸）。
//! 2. 给 libaom 的 `aom_dsp/bitreader.h` + `av1/decoder/decodeframe.c` 重打符号 trace 插桩，
//!    `AV1_TRACE_SYM_FRAME=33` 与 `MARK tile frame=33` 段逐符号 diff ⇒ 首处分叉 =
//!    第 150299 个符号（`txb_skip`，符号值相同、CDF 不同 ⇒ **上下文/状态**问题，不是语法结构）。
//! 3. 两边都开变换块级 trace（我们 `AV1_TRACE_TBXCTX=1`、libaom `LERXU_TBX_TRACE=1`），
//!    按行序对齐 ⇒ 第一个不一致的块是 txb 8841（plane 2、TX_4X4、`x4=155`）：
//!    我们 `skip_ctx=8 a0=1`、参考 `skip_ctx=7 a0=0`。
//! 4. 追那个槽位是谁写的（`AV1_TRACE_CTXW=1` 的 `pub`/`rst`）⇒ 是 txb 8821 写下的 `level=1`；
//!    再给 libaom 的 `av1_reset_entropy_context` 加清除插桩（打 `mi`/平面列号）⇒
//!    **libaom 在 txb 8829 处清过 `mi=(99,311)` 的色度列 155（`n=1`），我们一次都没清**
//!    —— 一眼看出是清范围的算法错了。
//!
//! 修完的验收：第 34 帧的 **330196 个符号与 libaom 逐符号完全一致**（含每个符号的
//! `n` / `sym` / 自适应 CDF），`--count=120` 全通。回归钉子见
//! `coeff.rs::tests::reset_block_clears_the_chroma_slots_the_spec_range_covers`。
//!
//! 像素层此时的水位（`tools/av1ref/refcmp.py`，dav1d 参考）：帧 0 **逐像素一致**；
//! 帧 1–119 平均 **0.2% 的像素有差异**（`max` 上界 23，多数只差 1）⇒ 剩下的是
//! **像素层**（环路恢复 / 去块 / CDEF 的舍入细节），与语法无关。
//!
//! ## 剩下那点像素差：2026-10-01 下半场把 0.2% 打到了 0.001%
//!
//! 先把结论摆在这里（每一步都用脚本量化过，别凭印象）：
//!
//! | 阶段 | 与 aomdec 逐样本比对（3.1M 样本/帧，滤波器全开） |
//! |---|---|
//! | 上半场结束 | 帧 1 差 183 个、帧 2 差 584、帧 3 差 911（**且逐帧放大**） |
//! | 修好 OBMC（见下）后 | 帧 0/1 **完全一致**，帧 2~19 稳定在 **26~53 个**、`max` 恒为 1、**不再放大** |
//!
//! 也就是说：现在的残差是**每帧几十个样本、只差 ±1**，而且**不随帧号漂移**（不再是指数式的
//! 像素误差放大，而是若干个独立的、局部的舍入平局）。
//!
//! ### 定位方法：外科式中和实验（`tools/av1ref/probe_neutralize.py`）
//!
//! **两边同时关掉某一个预测工具**，只看整帧差异是否归零 —— 不依赖任何帧号映射，
//! 也绕开"逐符号一致但像素有差"这种最难咬的情况。配套的 libaom 侧开关都是在
//! **预测阶段**覆盖读出来的语法值，**不动熵解码**（`LERXU_NO_OBMC` 覆盖
//! `read_motion_mode` 的返回值；`LERXU_NO_WARP` / `..._LOCALWARP` / `..._GMWARP`
//! 打在 `allow_warp()` 里）。判读表（帧 1 的差异样本数）：
//!
//! | 配置 | 帧 1 |
//! |---|---|
//! | 原样 | 183 |
//! | **两边同时关 OBMC** | **0** |
//! | 两边同时关 warp（局部 + 全局） | 0（亮度）/ 色度仍在 |
//! | 只关**局部** warp | 亮度全帧归零 |
//! | 只关全局运动 warp | 与"原样"**完全相同**（这份素材没用到全局运动 warp） |
//!
//! ⇒ **OBMC 是真 bug（已修）**；亮度残留是**块级 LOCALWARP**；色度残留是**另一件事**。
//!
//! ### 已修的两处 OBMC bug（都在 `inter.rs`）
//!
//! 1. **邻块预测的插值滤波器取错了对象**。规范 §7.11.3.4 的 `block_inter_prediction`
//!    用 `candRow/candCol` 去查 **`InterpFilters[candRow][candCol]`** —— OBMC 传进去的是
//!    **邻居块**坐标，所以要用**邻居自己的**滤波器；我们原来用的是**当前块**的。
//!    改完：帧 1 的亮度差异 **136 → 0**。
//! 2. **`get_plane_residual_size >= BLOCK_8X8` 这个门被当成了整体早退**。规范把它写在
//!    `if ( AvailU )` 块**内部**，libaom 的 `av1_skip_u4x4_pred_in_obmc(bsize, pd, dir)`
//!    写得更清楚：`BLOCK_4X4 / 8X4 / 4X8` 时返回 `dir == 0` —— **只挡上边那一条，
//!    左边那一条无条件做**。我们原来两个方向都挡了 ⇒ 子 8×8 的色度（平面块 4×4/4×8/8×4）
//!    **左边整条漏叠**。改完：帧 1 的色度差异 **24 → 0**，帧 0/1 逐样本全等。
//!
//! ### 归因必须按显示序 —— 这里有个一直骗人的坑
//!
//! `AV1_TRACE_BLKATTR` 的块轨迹是**解码序**，而落盘的帧是**显示序**：B 金字塔下
//! `--count=3` 会产生 8 段块轨迹（隐藏的 alt-ref 也带瓦片），**两者下标不相等**。
//! 直接按下标对，归因结果是**错的** —— 上半场那句"135/136 个差异点在 `skip` 块里"
//! 就是这么来的，**已作废**。
//!
//! 正确做法（`tools/av1ref/attr_by_frame.py`）：块轨迹每行带 `oh=<order_hint>` 与
//! `sf=<show_frame>`，**显示帧 j ↔ order_hint == j 的那一段**；`show_existing_frame`
//! 的显示帧**没有瓦片数据**（不在轨迹里），但它的内容就是更早解码的那个隐藏帧，
//! 而那个隐藏帧的 order_hint 正好等于显示序号 —— 所以按 order_hint 找段是对的。
//!
//! ### 剩下的两块残差（都还没修完）
//!
//! **A. 亮度：块级 LOCALWARP，每帧 2~5 个样本 ±1。**
//! 参数已经排除了：两边逐块对拍 **1704 条 warp 调用的 `wmmat` 与
//! `alpha/beta/gamma/delta` 100% 一致**（`AV1_TRACE_WARP` / `LERXU_TRACE_WARP`），
//! 所以差在**滤波运算**。翻到一处规范与参考实现的**实质分歧**：libaom 的
//! `av1_warp_affine_c` 在 `sx4 += alpha * (-4) + beta * (-4)` 之后多一步
//! `sx4 &= ~((1 << WARP_PARAM_REDUCE_BITS) - 1)`（C 与 NEON/SSE4/AVX2 四个变体**都有**），
//! 而规范正文 §7.11.3.5 没有这一步。可是**实测走"照 libaom 源码"反而差得更多**
//! （11 帧亮度残差 46 → 575）⇒ aomdec 运行时的净行为**更接近规范正文**，
//! 推测它走 SIMD 路径、而那条路径与该步掩码并不等价。目前**默认走规范写法**，
//! 留了 `AV1_WARP_REFFMT=1` 开关继续追。
//!
//! **B. 色度：只在复合块里，每帧 26~53 个样本 ±1（几乎全是"我们比参考低 1"）。**
//! 归因（`attr_by_frame.py`，帧 3~7 全部命中）：差异块 100% 是**复合块**
//! （`ct` = DIFFWTD / AVERAGE / DISTANCE 都有，`ref1` 是 BWDREF），且 `skip` 居多。
//! 已核对并**排除**的：差分权重掩码公式（我们 `38 + ((|Δ|+8)>>4)/16` 与 libaom 的
//! `diffwtd_mask_d16` 逐字一致，且掩码只由**亮度**预测差生成、色度按 2×2 平均下采样 ——
//! 也都对上了）、d16 掩码混合的**双重取整**（libaom 的
//! `aom_lowbd_blend_a64_d16_mask_c` 是 `(m*s0+(64-m)*s1) >> 6` 再 `- round_offset`
//! 再 `Round2(_, round_bits)`，与规范的 `Round2(m*p0 + (64-m)*p1, 6 + InterPostRound)`
//! 用 `floor(floor(x/a)/b) == floor(x/(ab))` 可证等价）。
//! ⇒ 嫌疑落在**色度的 d16 预测值本身**差 ±1：复合的 `InterRound1` 是 **7**（非复合是 11），
//! 第一趟留下的 ±1 在非复合里会被 >>11 抹掉、在复合里会被 >>7 原样留下 ——
//! 这也解释了"为什么亮度输出看不出来、只在复合的色度上显形"。
//!
//! ### 还没做的一步
//!
//! 给两边的**复合色度预测**加一条 d16 值轨迹（我们侧照 `AV1_TRACE_CMP_AT` /
//! `AV1_TRACE_DIFFWTD_AT` 的样子扩展；libaom 侧挂在
//! `av1_make_masked_inter_predictor` 里 `tmp_buf16` 生成之后），
//! 找到**第一处 `p0/p1` 差 1 的块**，再对那一块的 `block_inter_prediction`
//! 逐级（横向中间量 → 纵向）手算 —— `InterRound1 = 7` 这条路上的取整平局是头号嫌疑。
//!
//! 分区树（M4a）的验收口径：**恰好覆盖**（每个 4×4 位置被写且只被写一次）
//! + **大瓦片遍历完还剩着位**（分区符号只占一小部分）。这两条抓的是
//! `Partition_Subsize` 表、`hasRows/hasCols` 边界、CDF 上下文（`MiSizes` 邻居形状）
//! 这三处最容易错的地方。真素材实测：36845 棵、平均每棵 5082 个节点、最大深度 5、
//! 分区分布是典型的真实编码器形状（NONE 39% / SPLIT 25% / HORZ 13% / VERT 8.7%，
//! 还有 3:4 与 1:4 分区）。
//!
//! ## M5（像素重建）的验收口径：**用"源内容已知"的参照流当锚**
//!
//! M5 跟前几层不一样：语法层有 `exit_symbol()` 这种**绝对判据**，像素层却没有
//! 参考解码器可比（本机没有 ffmpeg/dav1d/aomdec，DEVELOPMENT.md 硬约定第 8 条也不许依赖
//! 第三方解码器）。所以 M5 的验收靠两条：
//!
//! 1. **单测钉解析解**（[`intra`] / [`transform`]）：平坦边上的 DC 必须等于那个值、
//!    `V_PRED` 必须逐列复制 `AboveRow`、无邻居必须给 `1 << (BitDepth-1)`、
//!    只有 DC 系数时反变换必须给出平坦块……这些都能手算，不需要参考解码器。
//! 2. **`tools/av1probe/samples/` 里那批流的源内容是已知的**（生成器画的）：
//!    `#808080` 全 128、`#101010` 全 16、`#f0f0f0` 全 240、`L43` 是四个象限。
//!    而 `#808080` 恰好等于帧内 DC 预测的默认值 ⇒ **残差恒为 0** ⇒
//!    "解出来的像素"必须逐样本等于 128。这条是**不依赖参考解码器的真像素验收**，
//!    而且它把整条链路（瓦片 → 语法 → 预测 → 平面写回）一起钉住了。
//!
//! M5 的顺序（也是踩坑最少的顺序）：
//! ① 帧内预测（[`intra`]）→ ② 反量化 + 反变换（[`transform`]）→
//! ③ 帧级像素缓冲 + `BlockDecoded`（`haveAboveRight` / `haveBelowLeft` 的依据）
//! → ④ 环路滤波（去块 [`deblock`] → CDEF [`cdef`] → 环路恢复 [`lr`]）→ ⑤ 输出色彩转换。
//! **除环路恢复与超分，①–⑤ 都已落地**，[`av1`] 把它们接成了完整的帧管线
//! （`decode_tile` → `filters::decode_frame_wrapup` → `nv12_frame`）。
//!
//! 现在的**像素级验收**（都在 `me-cli` 的 `real_av1_tests` 里，**不需要参考解码器**）：
//!
//! - `#808080`（源值恰好等于帧内 DC 预测的默认值 ⇒ 残差恒零）解出 **8064 个采样全 128**；
//! - **10 条带非零残差的平坦流**（16 / 64 / 112 / 144 / 154 / 192 / 240 这些必须靠
//!   残差重建的灰度）解出 **30 个平面全部像素级平坦**、色度恒为 128
//!   —— 反量化或反变换里任何一处偏差都会让平坦性破掉；
//! - **四象限流**解出 `[16, 160, 64, 240]` 四个**各自完全平坦**且互不相同的象限
//!   —— 分区边界、`haveAbove/haveLeft` 推导、残差叠加位置错一格都会花掉。
//!
//! 上面这几条是**合成流**上的验收。真实视频那一路（环路恢复 / 超分 / 帧间预测的
//! warp 与 interintra / 颗粒合成）参照流走不到，改由 [`tools/av1ref/`](../../../tools/av1ref/)
//! 的 aomenc 受控流 + dav1d 逐像素对拍负责 —— 其中 interintra 是 2026-10-01 补上的
//! （见上面分层表那一行；用例见 `make_cases.py --interintra`），**屏幕内容流的
//! `intrabc` 与 palette 也已在同日补齐**（`make_cases.py --intrabc` / `--palette`）。
//! 仍未覆盖的是"帧右边界超块伸出区"
//! 这个已知问题（见 [`upscale`] 抬头）。
//!
//! ## 性能：先量化差距，再逐层削（2026-10-01 晚）
//!
//! 起因是"AV1 播几帧卡一下"。第一步不是改代码，而是**量清楚差距**：
//!
//! | 同机同素材（1920×1080 AV1，B 站 ASMR）| 单线程 /帧（多次取 min）| 8 线程 /帧 |
//! |---|---|---|
//! | **dav1d**（参考实现，PyAV 调）| **11.4 ms** | **4.9 ms** |
//! | 我们（优化前）| ~1015 ms | ~1017 ms |
//! | 我们（现在）| **~360 ms** | **~300 ms** |
//!
//! ⚠️ **测量口径（这一条踩过两次，务必照做）**：这台机器**既不能信墙钟、也不能信
//! `user` 时间** —— 前者随系统负载波动（同一二进制连跑两次差 50%+），后者随 **CPU 频率
//! 缩放**波动（同一二进制两次实测 `user` 40.67 s / 31.19 s，差 30%）。
//! 唯一稳的做法：**同一素材、同一参数、两个二进制交替各跑 N 轮，比 `min` 与中位数**
//! （`min` 是最不易被干扰的估计量）。用引擎自报的 `elapsedMs`（`--count=20` 量级）
//! 就够，不必上 `/usr/bin/time`。
//!
//! ⚠️ **结论要纠正一句**：不是"Intel 机做不到 AV1 实时" —— 同一台机器上 dav1d
//! 单线程就有 88 fps。**差距全在我们的实现里**（当初写成"硬件不行"是错的）。
//! 现在离 dav1d 单线程还差 ~40 倍，dav1d 用掉的是两样东西：
//! **SIMD 内核**（AVX2 手写汇编）与**线程架构**（row-mt / frame-parallel）。

//!
//! ### 这一轮做掉的（每一处都"改动前后逐字节一致"，见下）
//!
//! 1. **诊断开关走 [`flags`]**：热路径里直接 `std::env::var` 要拿环境锁 + 线性扫描，
//!    `getenv` 一度占采样 **10%**（逐块/逐变换块调用，正常播放时一个都不该命中）。
//! 2. **`inter::block_inter_prediction` 的两条快路径**（这是最大的一笔，MC 曾占忙时 ~53%）：
//!    - **整数相位**（不缩放 + 两轴相位 0）：8 抽头滤波器在相位 0 是 δ
//!      （`SUBPEL_FILTERS[..][0] == DELTA_FILTER`，有单测钉住），两趟卷积退化成"乘 128 +
//!      两次取整"。⚠️ **不能直接写 `row[sx]`**：`InterRound0/1` 随位深与复合与否变
//!      （8bit 复合是 3/7，纵向输出本该是 `16·src`），照原公式走两趟取整才逐位一致。
//!    - **不缩放但相位非 0**：相位在两轴上都是常数 ⇒ 系数只查一行/一列，
//!      源坐标就是 `base + 下标`，累加用 i32（值域安全）。
//!    - 缩放的参考（超分/尺寸不同）保持原实现不动 —— 那档占比极低。
//! 3. **`lr::box_filter` 可分离滑动和**：规范的"每像素扫 (2r+1)² 邻域"是可分离的，
//!    值完全一样（整数加法无舍入），25 次取样变常数次加减。
//! 4. **`deblock` 一次读进 14 项窗口**：原本 16 抽头那条路每个样本位置要回平面读上百次
//!    （`wide_filter` 曾占忙时 13%）；现在掩码与滤波器都从窗口取。`narrow/wide_filter`
//!    的抽头全部来自窗口，`f[]` 用定长数组。
//! 5. **中间缓冲全部栈上**：`sgr_filter`（a/b 36 项 + 两趟 F 16 项）、
//!    `wiener_filter`（40 项）、MC 横向中间量（4096 项，大块退堆）。
//!    ⚠️ 中间试过"线程局部池复用"，结果 **TLS 访问自己占了采样 63.5%**（逐块调用），
//!    栈数组才是对的 —— 见下面教训。
//! 6. **帧内数据并行**（[`parallel`]）：CDEF 与环路恢复都是"读一份缓冲、写另一份"，
//!    按行切即可并行；写句柄 [`parallel::RowsSink`] 是裸指针 + 行区间不变量
//!    （**必须持平面基址**：`set` 用绝对行号，指向切片起点会把偏移重复算一遍 → SIGSEGV）。
//!    `ME_THREADS=n` 可调（1 = 退回串行，便于对拍）。
//!
//! **验收（必须每次改动都做）**：`ME_THREADS=1/2/4/8` × 改动前后，解同一素材同帧数，
//! 输出目录**逐字节 md5 相同**；再与 dav1d 逐样本对拍（帧 0/1 完全一致、
//! 其余帧每帧十几个样本 `max=1` —— 与优化前**逐字节相同**）。
//!
//! ### 第三轮：手写 SIMD（[`simd`]）
//!
//! 按 dav1d `src/x86/*.asm`、libaom `av1/common/*_sse2.c` 的**做法**自己写
//! （只用 `std::arch` 的 intrinsic，不引库、不抄代码）：MC 的
//! **整数相位合成**（`mc_delta8`）、**横向 8 抽头**（`mc_horiz8`）、**纵向 8 抽头**（`mc_vert8`），
//! 一次算 8 个输出（AVX2 的 8 个 i32 通道）。要点：
//!
//! - **运行时探测** + **只吃内点**：`simd::avx2_available()`（`ME_NO_SIMD=1` 可强制标量）；
//!   窗口没完全落在帧内的块、以及 `w % 8` 的尾巴一律回落标量路径 —— 标量路径已被
//!   逐样本对拍验过，两条路合起来仍然逐位一致。
//! - **算术按 i32 累加**：8bit 最坏 `240·255 = 61200`、12bit `240·4095 ≈ 9.8e5`，
//!   纵向 `≈ 1.2e6`，都在 i32 内；顺序变化不影响整数结果。
//!   ⚠️ 这里的 `240` 是**系数绝对值和**，不是 `Σc = 128` —— 两者混用曾导致
//!   横向 16 位通道内核溢出（`simd.rs` 顶部有完整记录）。
//! - ⚠️ **踩到的坑**：`mc_vert8` 第一版漏了**列偏移**（只读 `(row+t)*stride`）——
//!   单测里列偏移恒为 0 所以照样通过，真素材上第 8 列之后的每一批都读错位置；
//!   是"开/关 SIMD 输出逐字节一致"这条判据把它抓出来的。**单测覆盖不到的参数，
//!   要靠端到端的逐字节对拍兜底。**
//!
//! ### 第四轮：CDEF 的 SIMD + 去掉整帧拷贝 + 帧缓冲池
//!
//! 一、**CDEF 的 SIMD**（[`simd::cdef_block8`]，上一轮采样它是第一名，占忙时 33%）
//!
//! - 关键观察：**固定一行时，"候选相对当前像素的位移"对 8 个像素是同一个常数**
//!   ⇒ 12 个候选每个都是**连续 8 个 u16**，一次 `loadu` + 零扩展就够。
//! - `constrain( diff, thr, adj )` 直接照着标量式子向量化：`abs` / `srav`（阈值右移
//!   用**变量移位**，因为 `adj` 随强度变）/ `min` / `max` / `sign_epi32`（一次拿到
//!   "取符号 + `diff == 0` 归零"）/ `mullo`，最后 `cmpgt + and` 得到 `adjust`。
//! - 色度（`w = 4`）**复用同一个 8 通道内核**，只写前 4 个通道 —— 多读的那 4 个样本
//!   落在 `PLANE_PAD` 里（值无所谓，直接丢），换来"只有一个内核"。
//! - 效果：采样里 CDEF 从 **33% → 1.8%**；单线程 CPU 1.20x。
//!
//! 二、**去掉每帧的整帧拷贝**（这是 memmove 从 14.8% 掉到 2.7% 的原因）
//!
//! - **没开超分时上采样是恒等变换** ⇒ [`filters::decode_frame_wrapup`] 直接把两份帧
//!   **搬过去**（`(frame, cdef)`），不再 `upscale::apply()` 各拷一份（省 2 × 6 MB/帧）。
//! - 环路恢复的输出原来是 `up_cdef.clone()` 再就地覆盖 —— 现在改成 `CurrFrame::new`
//!   + **每个块都写满**：`RESTORE_NONE` 那一档从"什么都不做（吃预拷）"改成
//!   **按块从 `CdefFrame` 搬样本**；`frame_restoration_type[plane] == RESTORE_NONE`
//!   的平面则整平面 `copy_from_slice`（连 padding 一起，与旧行为逐字节一致）。
//!   ⚠️ 这条的**前提就是"覆盖满"**：改那段循环时务必保持。
//!
//! 三、**帧缓冲池**（[`pool`]，配 `intra::Plane` 手写的 `Clone`/`Drop`）
//!
//! `Plane` 的缓冲按长度回收复用：`new` 优先取池里的（重填中灰），`clone` 直接
//! `copy_from_slice`（**没有分配、也没有多余的填充写**），`Drop` 还回去。
//! 省掉的是"每帧新开一块"带来的 mmap + 缺页 + 内核清零（采样里 bzero 3.1% +
//! madvise 1.9% + `CurrFrame::new` 2.7%）。池是线程局部的、有上限（8 块 ≈ 30 MB）。
//!
//! ### 第五轮：去块并行（[`deblock`]，采样第一名 20%）
//!
//! 去块是**就地**滤波，但按 `(dx, dy)` 一推就清楚：`loop_filter_edge` 的收尾是
//! `for i in 0..MI_SIZE { sample_filter(…, xp + dy·i, yp + dx·i, …) }`，而
//! `sample_filter` 的读窗口只沿 `(dx, dy)` 铺开 ⇒ **pass 0 只碰 4 行、pass 1 只碰 4 列**。
//! 于是 pass 0 **按行带切**、pass 1 **按列带切**，带内仍按规范顺序（`col` / `row` 升序），
//! 合并起来与串行**逐位相同**（四种线程数 + 串行的输出 md5 全等）。
//!
//! ⚠️ 反过来"pass 1 按行切"是**错的**：同一 `col` 上相邻 `row` 会互相读。
//! 实现用 [`deblock::PlaneView`]（裸指针 + 带的不变量）承载，`debug` 构建下断言不越带。
//!
//! 效果：8 线程墙钟 14.91 s → **12.44 s（1.20x）**；串行路径的 CPU 时间没有退化。
//!
//! ### 第六轮：`inter` 的**逐块堆分配**（[`inter::scratch_of`]）
//!
//! 采样里 `inter::compute_prediction` 占 12%，其中一大块是"**每块一次 `vec![0i32; w*h]`**"：
//! `predict_inter` 里 `preds: Vec<Vec<i32>>`（一次 `Vec<Vec>` + 每路一个 `Vec`），
//! `block_inter_prediction` 内部还有两个，OBMC 每个邻居一个。
//! 1080p 一帧几万块 × 1~2 路 ⇒ malloc 与 `bzero` 各几万次（`_platform_bzero` 3.9% 就是它）。
//!
//! 改法（**不改一个像素的算法，只换落点**）：
//! * `block_inter_prediction` / `warp::block_warp` 的签名从"返回 `Vec<i32>`"改成
//!   "写进调用方给的 `&mut [i32]`"；
//! * 缓冲由 **`BlockCtx` 持有**（`pred_scratch: [Vec<i32>; 2]`）—— `BlockCtx` 是
//!   **每瓦片**建一次、`decode_block` 每块调一次，正是"比块长、比帧短"的那个生命周期；
//! * `scratch_of(v, n)`：**长度没变就什么都不做**（连续同尺寸的块是常态），
//!   变长才 `clear + resize(n, 0)` —— 那次填充是死数据，但 `resize` 必须给初值。
//!
//! 效果（20 帧 × 5 轮交错，`min`/中位数）：**1.04x / 1.06x**；
//! 采样里 `compute_prediction` −32%、`_platform_bzero` −33%、memmove −30%。
//! ⚠️ 收益不大但**方向明确**，且这一步把"逐块分配"这个结构性浪费彻底去掉了
//! （后面给 `inter` 做 SIMD 时不会再被 malloc 挡住）。
//!
//! ## 剩下的热点与下一刀（2026-10-01 深夜采样，单线程忙时）
//! | 项 | 占比 | 结论 |
//! |---|---|---|
//! | 去块（`loop_filter_edge` + `wide_filter`）| **21%** | ✅ 已并行（[`deblock`] 抬头）且内核已 SIMD（见下"第七轮"）|
//! | 反变换（`forward_1d` + `inverse_transform_2d`）| ~~11%~~ → 4.6% | ✅ 第八轮：去分配 + 4 条线 SIMD（1.15x）|
//! | `inter::compute_prediction`（已无逐块分配）| ~~8%~~ → ~6% | ✅ 第十轮：六条写回路径去逐像素 `set`（1.11x）；剩下的在 OBMC/复合的掩码计算 |
//! | 环路恢复（`box_filter` + `restore_block`）| ~~12%~~ → ~11% | ✅ 第九轮：去除法/去逐样本钳位/几何每平面一次（1.07x）；剩下的可 SIMD |
//! | MC 三个内核（`mc_horiz8/vert8/delta8`）| 7% | ✅ 横向已换 16 位通道（第十二轮，1.07x）；纵向/整像素档还是 i32 |
//! | memmove + bzero + `nv12_frame` | 10% | CDEF 的那次整帧 `clone()` 还在；`nv12_frame` 只在 `decode --out` 落盘时才有 |
//!
//! ⚠️ **这张表是 10-01 深夜的数字，已经过时**：10-02 上午先去掉了窗口重复读
//! （一次读进 14 项）与 `wide_filter` 的常量泛型化（去块那时已降到约 6.4%），
//! 当日下午又做了第七轮的去块 SIMD（再降到约 4.2%）。**动刀前重新采样，别看旧表。**
//!
//! ### 第七轮：去块的 SIMD（[`simd::deblock_edge4`]，2026-10-02）
//!
//! 一次 `loop_filter_edge` 处理 `MI_SIZE = 4` 条平行线 —— 正好 4 个 i32 通道
//! （128 位）。掩码（hev/filter/flat/flat2）与窄/宽滤波器照标量式逐条换成通道级，
//! 逐线分支（`hev` 保不保 `q1/p1`、选窄还是宽、`flat2` 走不走 16 抽头）用 `blendv`
//! 融合；**竖边的难点在寻址**（4 条线跨 stride）：读入/写出各做一次 4×8 / 4×4
//! 转置（`dbl_load4x8` / `dbl_store_v4`），横边则是每档 `k` 连续 4 个 u16 直接加载。
//! 只吃内点、边界回落标量 —— 与本文件所有 SIMD 内核同一个约定。
//!
//! - 验收：`deblock::tests::simd_edge_matches_scalar_bit_for_bit`（7 组 平面×滤波尺寸×
//!   位深 × 结构化/随机扫描，**整个平面缓冲逐字节**比）+ 真素材 `--out` 20 帧与优化前
//!   **逐字节相同** + `ME_NO_SIMD=1` 三路一致。
//! - 效果（单线程 40 帧 × 3 轮取 min、两二进制交替）：12247 → 11359 ms（**1.06x**）；
//!   采样里去块 **6.42% → 4.15%**（内核自身约 1.55x）。
//! - 踩过的两个坑（都是"掩码/参数选错"而不是算术）：`_mm_blendv_epi8(a, b, m)` 是
//!   **m 置位取 b**（hev 的"保留原值"分支一开始接反）；色度 8 抽头的宽滤波器 `n = 2`
//!   （不是亮度的 3），且 `V[k]` 的通道取法要跟着 `n` 走。
//!
//! ### 第八轮：反变换的去分配 + 4 条线 SIMD（2026-10-02）
//!
//! 1. **去分配**（1.051x）：`permute` 的 `to_vec()`（逐行/逐列 malloc）换成
//!    `[MaybeUninit; 64]` 栈暂存且**不清零**（`n0` 最小只有 4）；`line` 换 `[i64; 64]`；
//!    `levels`/`t`/`pred`/`residual` 挂到 `BlockCtx::tx_scratch`（逐瓦片一份，
//!    与 `pred_scratch` 同一个套路）。**"逐块一次 vec!" 在这个模块发生过两次
//!    （inter、transform），第三处再看到时别再犹豫。**
//! 2. **SIMD**（[`simd::inv_txfm_rows`] / [`simd::inv_txfm_cols`]）：1D 内核按
//!    **4 条平行线一组**（i64×4）。列趟最省事（4 列在同一行里连续）；行趟跨 stride，
//!    用 4×4 i32 转置收集、4×4 i64 转置写回。**值域分析**实测：乘法输入 |t| ≤ 2^19.5
//!    （12bit 极端；8bit 真素材 2^13.5）⇒ `_mm256_mul_epi32` 精确；积/和到 ~2^32
//!    ⇒ 通道必须 i64。
//! 3. **两个坑**：`vt_*` 辅助函数忘写 `#[target_feature(enable = "avx2")]` ⇒
//!    每条 AVX2 intrinsic 变成真实函数调用，**比标量慢 47%**（`sample` 里
//!    `avx2::_mm256_*` 屠榜，一眼可辨）；permute 的 2KB 数组全量清零在白写的 62%
//!    小方块（4×4/8×8）上是纯浪费。
//! 4. 效果（单线程 40 帧、两二进制交替多轮取 min）：去块 SIMD 版 ~10850 →
//!    去分配 ~10200（1.05x）→ **9355 ms**（合计 **1.15x**）；采样里反变换占忙时
//!    8.7% → 4.6%。⚠️ 机器噪声大，只看"交替多轮取 min"。
//!
//! ### 第九轮：环路恢复的"每块重算 / 每样本重查"（2026-10-02）
//!
//! LR 是逐 4×4 块调用的（1080p 一帧几十万块），三处改动都只改落点、不改结果：
//! ① `a2` 的整数除法换 256 项常量表（`X_BY_XPLUS1`；**`z` 会为负**——`p*s` 的 i32
//! 溢出，改动前就有，负档必须走原式兜底）；② `src.get` 的两次钳位 + stripe 判定
//! 从逐样本改成逐行/逐列表；③ 恢复单元几何每平面算一次（`unitSize` 是 2 的幂 ⇒
//! 移位），`RESTORE_NONE` 与三个滤波器的输出改 `set_row` 按行写。
//!
//! 效果：LR 占忙时 ~25% → ~11%（`box_filter` 15% → ~7%），整帧单线程 **1.07x**；
//! 真素材 20 帧逐字节一致。
//!
//! ### 第十轮：帧间预测的写回路径去逐像素 `dst.set`（2026-10-02）
//!
//! 六条写回路径（单参考 / AVERAGE / DISTANCE / 楔形与差分的 `blend_masked` /
//! interintra / OBMC）+ intrabc 拷贝统一改成**按行落盘**：纯"钳位+收窄"的两条走
//! [`simd::store_row_clamped`]（AVX2：`min` + `packus` + 16 字节写，一次 8 个样本），
//! 其余先在行缓冲里按原式算完再整行 `copy_from_slice`。逐像素 `Plane::set`
//! （每像素一次下标乘法 + 一次边界检查）就此从 inter 里消失。
//!
//! 效果：单线程 9818 → 8821 ms（**1.11x**），`compute_prediction` 占忙时 ~11% → ~6%。
//! 真素材 20 帧逐字节一致（改动前后三个二进制互相对拍）。
//!
//! ### 第十一轮：MC/OBMC 的 scratch 复用 + `project_frame` 常量外提（2026-10-02）
//!
//! 三处"每次调用都白花"：① `block_inter_prediction` 的横向中间量是 `[0i32; 4096]`
//! 栈数组 —— **每次调用 memset 16KB**（`bzero` 在采样里的头号来源），大块还逐块
//! `vec![]`；② `obmc_blend`/`predict_intrabc` 的逐块局部 scratch（OBMC 一帧约 2 千块）；
//! ③ `project_frame` 把 7 个目标帧的常量放进逐格循环（一格 7 次 × 3.2 万格 × 5 源帧）。
//! 分别改成：调用方持有（`pred_scratch[2]`）+ `scratch_of` 只增不减、复用同一份、
//! 常量提到循环外 + `mv_projection_clipped`。
//!
//! 效果：8 线程 9360 → 8442 ms（**1.11x**，≈211 ms/帧）；逐字节一致。
//! ⚠️ 顺带量清了**播放口径的真实瓶颈**：8 线程相对单线程只有 ~1.45x ——
//! 串行核心（熵+预测+变换+簿记）占单线程 273 ms 里的 **~177 ms**，并行的滤波
//! （去块/CDEF/LR）约 97 ms 且已按行带分好。⇒ **要摸到实时（30fps=33 ms/帧），
//! 关键在于把串行核心并行化（row-mt / frame-parallel，2~3x）＋继续削每块开销**，
//! 而不是只磨并行侧的内核。
//!
//! ### 第十二轮：MC 横向内核换 16 位通道（2026-10-02）
//!
//! ⚠️ **这一轮埋了一个像素级回归，2026-10-03 才修掉**（根因与修复见 `simd.rs`
//! 顶部）：当初按"`Σ|coef| = 128` ⇒ `128·255 = 32640` 装得进 i16"设计，
//! 而真实滤波器有 48/96 个相位 `Σ|c| > 128`（最坏 240）⇒ **i16 累加回绕**。
//! 症状：整像素 MV 全对，分数 MV 偶尔几个像素错到 255。
//! 修法是**带偏置的 i16 累加**（每个抽头仍是 `mullo_epi16` + `add_epi16`，
//! 指令数不变、仍一次 16 个输出），逐位一致回来且没有性能损失。
//!
//! 8bit 下用 i16 通道、一次覆盖 **16 个输出**（i32 版是 8 个）。
//! 10/12bit 样本太大，仍走 i32 版（`plane_data.bit_depth == 8` 分流）。
//! 效果：8 线程 7998 → 7465 ms（**1.07x**，≈187 ms/帧）；逐字节一致 +
//! `horiz16_matches_scalar_bit_for_bit`（现含全部 96 相位与 0/255 混排行）。
//!
//! ### 第十三轮（诊断）：把"语法 / 重建 / 滤波"拆开量 —— row-mt 的天花板
//!
//! 两个新开关（都是 no-op，只在设置时生效）：
//! * `AV1_SYNTAX_ONLY=1`：只读语法、不做重建（像素是垃圾；**参考帧槽仍照常更新** ——
//!   早退会让后续帧的 `is_scaled`/`num_warp_samples` 判据变样，语法跟着错位，这条踩过）；
//! * `AV1_PHASE_TIMING=1`：每帧打一行 `tiles / filters / ref / out` 耗时。
//!
//! 单线程实测（1080p，30 帧，两两交替取 min）：
//!
//! | 配置 | ms/帧 | 结论 |
//! |---|---|---|
//! | 完整 | 227.6 | — |
//! | 关滤波（去块+CDEF+LR）| 200.5 | 滤波 27 ms（12%）|
//! | **只解语法** | **45.7** | **语法 46 ms（20%）、重建 ≈155 ms（68%）** |
//!
//! ⇒ **row-mt（语法一条线 + 重建按 SB 行波前并行）的天花板 ≈ max(46, 155/4)+滤波
//! ≈ 50~60 ms/帧（≈4x）**；而且语法侧**不依赖本帧重建**（只依赖参考帧已就绪）——
//! 这就是它可以拆的前提。`--count=1` 会连带解出隐藏的 alt-ref，所以"ms/显示帧"
//! 里含 ~1.67 个解码帧的成本，别拿它当"每解码帧"。
//!
//! ### 第十四轮（row-mt 阶段 1）：语法 / 重建两阶段拆分（顺序版，`ME_ROW_MT=1`）
//!
//! 依据第十三轮的拆账（语法 46ms / 重建 155ms / 滤波 27ms），把 `decode_tile`
//! 拆成两阶段：
//!
//! * **语法阶段**：`decode_block` 只读位 —— 模式信息照旧写网格/上下文/统计，
//!   系数照旧读进复用缓冲，但**不写一个像素**；把"重建要用的一切"记进工单
//!   （[`block::RowMtJobs`]：`BlockInfo`/`WarpPlan`/`IntraContext`/`ResidualConfig`
//!   的快照 + 每个 txb 的 `(plane, start, tx_sz, x, y, levels)`）。
//! * **重建阶段**：`decode_tile` 在超块循环之后调 [`block::BlockCtx::replay_jobs`]
//!   按**同一顺序**回放（`compute_prediction`、逐 txb 的帧内预测/残差叠加、
//!   `BlockDecoded` 标记）。`MaxLumaW/H` 是**重建侧**的量，跟着挪到回放里。
//!
//! 三个容易漏的点（都写进了代码注释）：① **调色板块**的预测要用"活的"调色板字段
//! （逐块覆盖）⇒ 在语法阶段遇到它先 **flush**（把已记录的回放掉）再就地重建；
//! ② `skip` 的块**也要记**（帧内预测按 txb 做，与有没有残差无关）；
//! ③ 语法**不依赖本帧重建**、只依赖参考帧就绪 —— 这条是拆分的合法性所在
//! （第十三轮踩过：语法-only 早退跳过参考帧入槽，后续帧语法立刻错位）。
//!
//! 验收：`ME_ROW_MT=1` 与现路径输出**逐字节一致**（真素材 20 帧 + 全量测试 875 项）。
//! 阶段 1 只求"等价"，所以比现路径**慢一点**（多一遍搬系数/回放）；阶段 2 再把回放
//! 按 SB 行波前并行，目标 ≈ max(46, 155/N) + 滤波 ≈ 50~60 ms/帧。
//!
//! ### 第十五轮（row-mt 阶段 2）：**竞态已清，与顺序回放逐字节一致**
//!
//! 阶段 2 = 回放并行。现在 `ME_ROW_MT_PAR=1` 在**任意线程数**下与 `ME_ROW_MT=1`
//! 逐字节一致（1/2/3/4/6/8 线程，各跑两遍；探针 `ME_TRACE_RACE=1` 零命中）。
//!
//! #### 竞态的根因（第一版）：水位只记列、不记行
//!
//! 第一版是"一条 SB 行 = 一个任务 + 一个**列水位** `progress`"。真素材用的是
//! **128×128 超块**，所以一条带有 **32 个 mi 行**高；而带内是**按超块光栅**推进的 ——
//! 一个 `64×16` 的块落在带顶时就能把"列水位"推到列尾，却只写了 4 行。而下一条带的
//! 读者要的是**上一带的最后一行**。于是读到还没重建的像素。
//!
//! 定位它靠的是新加的 **`ME_TRACE_RACE=1` 探针**（给回放维护一份 4×4 的"已写"位图，
//! 帧内预测读上一行/左一列时若那格还没写过就报 `RACEREAD`）：
//! **顺序回放零命中**（探针自检通过）、并行回放命中，且命中点全是"带顶块读上一带底行"。
//! ⚠️ 探针第一版有**假阴性**：`replay_txbs` 原先在 `reconstruct_block`（预测）之后就盖章、
//! 残差还没加 ⇒ 读者看到"已写但缺残差"的像素。盖章必须挪到 `add_residual` 之后。
//!
//! 修法：把水位从"块右边缘"改成**"整列超块做完"**（`wave_progress`：只在一个 SB 列
//! 的最后一个块之后前进；与 libaom row-mt 的 job 粒度一致）。
//!
//! #### 为什么最终改成"作业 + 拓扑序发牌"
//!
//! 修完竞态后，**并行度只有 1.1~1.5x**。用 `ME_TRACE_WAIT=1` 量"空等"发现：
//! 一条带 = 一个任务、按 `行号 % worker 数` 分配 ⇒ 1080p 只有 **9 条带**，
//! 4 个 worker 里每个要**串行**走 2~3 条整带，波前只在带边界起作用
//! （忙时从单线程 199ms 膨胀到 8 线程 640ms）。
//!
//! 现在改成 **libaom row-mt 的 job 模型**：作业 = `(带, 超块列)`（135 个），
//! 依赖只有三条 —— 上一带**同列**、上一带**次列**（`AboveRow` 读到 `x + 2w - 1`）、
//! 同带**左邻列**（`LeftCol`）。发牌顺序取 `φ = 2*band + col` 升序：
//! 三条依赖在这个量上都**严格更小** ⇒ 合法拓扑序，**不会死锁**。
//!
//! ⚠️ 三个踩过的坑（都写在代码注释里）：
//! 1. **不能用 `φ = band + col`**：那时"上一带次列"与自己是**同一层**，层内还是一条链，
//!    并行度被吃光（实测 1.4x，且加屏障也救不了）。
//! 2. **依赖等待不能写在 `if band > 0` 里**：带 0 的 `deps[2]`（同带左邻列）会被跳过，
//!    首个错点正好是 **x=128**（超块列 1 的起点）—— 这个指纹直接指认了根因。
//! 3. **`intrabc` / 依赖超出"本列+次列"的情形不要硬等整带**：整带等待在拓扑序发牌下
//!    **会死锁**（要等的作业排在后面，踩过一次 20 分钟挂死）。现在改成**整帧退回顺序回放**。
//!
//! #### 现在的口径与水位
//!
//! - **回放阶段**（进程内计时，14 帧）：t=1 → 2661ms、t=2 → 1540ms（1.7x）、
//!   t=4 → 1372ms（1.9x）、t=8 → 1755ms（1.5x，空闲占比 67%，8 线程**过订阅**）。
//!   ⇒ 这台 4 物理核 / 8 逻辑核的机器上 **4 线程是甜点**。
//! - ⚠️ **本机测墙钟极不可靠**：WorkBuddy 自身的 node/renderer/GPU 进程常占 40~55% CPU，
//!   同一配置两次能差 1.7 倍（实测 seq 256 → 645 ms/帧）。上面这些数是同一时间窗内的
//!   相对值，绝对毫秒只能当量级。
//! - **50~60 ms/帧的目标还没到**，而且**光靠回放并行到不了**：按第十三轮的拆账，
//!   语法 24ms（串行）+ 回放 128ms + **滤波 64ms（单线程）**、参考/输出若干。
//!   回放即使 4x 也只到 `24 + 32 + 64 ≈ 120ms`。要真到 50~60，**必须**再解决
//!   ① 滤波链路并行（去块已按行带并行，CDEF/LR 还是单线程）② 语法侧 SIMD/缩短。
//!
//! ### 第十六轮：环路恢复按 64 像素一档 + row-mt 等待改真睡眠（2026-10-03）
//!
//! **先重新采样**（`sample` 的 `Sort by top of stack`，单线程）：LR 的 `box_filter` +
//! `apply` 闭包 ≈ **23%**、MC（`compute_prediction` + 三个内核 + warp）≈ **23%**、
//! 去块 ≈ 10%、CDEF ≈ 6.7%、反变换 ≈ 4%。再用 `AV1_SYNTAX_ONLY` 拆账（单线程）：
//! 纯语法 **20~24ms** / 重建 ≈ 70ms / 滤波 ≈ 100ms（8 线程 ≈ 32ms）⇒ 8 线程整帧
//! 里**瓦片阶段（串行）已经是 70%**。
//!
//! 1. **环路恢复按 [`lr::LR_CHUNK`]（64 亮度像素）一档处理**（`lr.rs`）：原先按 4×4 块
//!    调用，`box_filter` 的 A/B 滑动和把同一批样本**重复算了 4~6 倍**，每 16 个像素还要
//!    付一次函数调用 + 定长缓冲清零。现在一档 64 像素 —— 两轴都是 2 的幂、恢复单元
//!    ≥64 且起点对齐 ⇒ 一档**必定落在同一个恢复单元内**（`lr_type_at` 的取值不变）；
//!    `get_source_sample` 的钳位是**逐样本**语义、与处理档的划分无关 ⇒ **逐位不变**
//!    （已用真素材 20 帧对 dav1d 逐像素 + `ME_NO_SIMD` 开/关 + 13 条受控流验过）。
//!    实测：滤波阶段 8 线程 **46 → 32ms**；整帧交替 A/B **≈1.10x**（196.6 → 178.8）。
//! 2. **row-mt 的等待从 `yield_now` 改成 20µs 短睡眠**（`block.rs::wait_until`）：
//!    4 物理核 / 8 逻辑核上，"让出"仍然在烧前端；短睡把核让给真正在重建的 worker。≈1.03x。
//! 3. **顺带给 row-mt 定了水位**（细节见两处注释）：记录体（`BlockJob` + `levels` arena）
//!    在真素材上是**每帧 20~40MB 的冷内存流量** ⇒ 回放比 inline 重建慢 ~1.2x，加上回放前
//!    的准备，**当时整条 row-mt 比 inline 慢 ~28ms/帧**（瓦片 110.6 vs 89.3）。
//!
//! ### 第十七轮：row-mt 语法阶段不再重复预测（2026-10-03 晚）—— **row-mt 第一次真正快过 inline**
//!
//! **病根不是记录体，是"整帧预测算了两遍"**：`decode_block` 里那条
//! `if let Some(frame) = self.frame.as_deref_mut() { compute_prediction(...) }`
//! **不判 `recording`**，于是在 row-mt 的语法阶段（本应只记工单、不写像素）也把整块
//! 预测跑了一遍，写进帧里；随后 `replay_one` 又用同一份 `warp` / `intra_ctx` 重算一次
//! —— 第一遍**纯属白跑**（第二遍覆盖它）。
//!
//! 证据链（第十六轮遗留的诊断派上了用场）：
//! ① `ME_TRACE_WAIT=1` 的 `RMSTAGES` 显示纯语法 16~26ms 而"语法+记录"58~61ms；
//! ② `AV1_TRACE_SYNMS=1` 同口径下 inline 65~67ms ≈ row-mt 58~61ms，差出来的 ~40ms
//!    正好是那遍被丢弃的 MC；③ 给回放加桩（`ME_RM_NO_REPLAY`，已删）后 `sample` 里
//!    依然是 `compute_prediction` / `mc_vert8` / `mc_horiz16` 屠榜 —— 它们只能在语法段跑。
//!
//! 修法（`block.rs` 帧间分支）：`if let Some(frame) = self.frame.as_deref_mut().filter(|_| !recording)`。
//! **调色板块不受影响**：flush 那一支把 `inline_block = true`，`recording` 因此为假、照旧就地
//! 预测；而 flush 本身要的"已重建像素"正是回放（`replay_jobs`）写出来的 —— 调色板路径本来就
//! 假定"语法阶段帧里没有像素"，这个改动与那条设计一致。
//!
//! 实测（36 帧，8 线程，同窗口交替取最优）：
//!
//! | | 改前 | 改后 |
//! |---|---|---|
//! | row-mt（顺序回放） | 9613ms（267ms/帧）| 7420ms（206ms/帧）|
//! | row-mt（并行回放） | ~7900ms | **6715ms（186ms/帧）** |
//! | inline（对照，未动） | 7066ms | 7255ms（噪声内）|
//!
//! ⇒ row-mt 并行 **6715 vs inline 7255**，第一次**快过 inline**（1.08x），比它自己改前快 **1.33x**；
//! `RMSTAGES` 的 `syntax=` 从 58~61ms 降到 **16~38ms**。默认路径不受影响
//! （`syntax_phase` 为假 ⇒ `recording` 恒假），旧/新二进制默认输出**逐字节相同**。
//!
//! #### 下一步（按"能拿回多少"排序）
//!
//! | 方向 | 现在 | 预期 | 参考谁 |
//! |---|---|---|---|
//! | ~~**row-mt 记录瘦身**~~（`quant` 复用缓冲 + `levels` 截断）| ✅ **第十八轮已做**，**1.37~1.49x** | ~~回放并行真正兑现 → 省 30~40ms~~ | — |
//! | **帧级流水**（第 N+1 帧的语法与第 N 帧的滤波重叠）| — | 省 20~30ms | dav1d `thread_task.c`、libaom 的 frame threading |
//! | MC 纵向 16 位通道 + `warp` 的 SIMD | 忙时 23% | MC 1.5~2x | dav1d `mc_vert` / `warp_affine` |
//! | LR 竖直方向也按档（h=64，需要按 worker 的堆缓冲）| 滤波 32ms(8T) | LR 再 1.3~1.5x | libaom `restoration.c` 按单元 |
//!
//! ### 第十八轮：row-mt **记录体瘦身**（2026-10-03 深夜）—— 再砍掉语法阶段的"记录税"
//!
//! 第十七轮修掉"整帧预测跑两遍"之后，`RMSTAGES` 的 `syntax=` 到了 16~38ms，但**它恒比纯语法
//! （`AV1_SYNTAX_ONLY=1`）慢 ~1.8x**：同帧对比（`--count=1`，4 线程）—— 帧 2 纯语法 `tiles`
//! 83.5ms vs row-mt `syntax` 175.1ms；帧 4 是 18.6 vs 53.5（2.88x）。差额就是**记录本身**。
//! 加三段计时（`dbg_sc`/`dbg_co`/`dbg_pu`，诊断已删）拆开后是两处根因：
//!
//! ① **`coeffs` 里的 `quant: [i32; 1024]` 栈数组（大头）**。
//!    `levels_out = None` 时它只喂 `cul_level` 累加 ⇒ LLVM 能把整个数组优化掉；
//!    `levels_out = Some` 时末尾要 `out[..n].copy_from_slice(&quant[..n])` ⇒ 数组**必须真物化**
//!    —— 实测 **~2µs/次**（LLVM 生成逐元素 store，**不是 `memset`**），一帧 3 万块就是几十 ms。
//!    **修法**：挪进 `TxScratch` 做复用缓冲（`TxScratch::quant` + `coeffs` 多收一个
//!    `quant: &mut [i32]`），每次只 `fill(0)` `min(w*h, MAX_TXB_COEFFS)` 个（真素材平均不到 100）。
//! ② **`push_txb` 按 `w*h` 整段拷（次之）**。`levels` 的有效长度只有 `min(w*h, MAX_TXB_COEFFS)`
//!    （64 尺寸的变换只把系数放在左上 32×32，`dequantize` 也只读 `min(w,32)×min(h,32)`），
//!    按 `w*h` 拷对 64×64 白拷 3/4。**修法**：写入侧与读取侧统一截断。
//!    （`scratch_len` 本身不是问题：全帧实测 3ms。）
//!
//! 实测（36 帧 8 线程 row-mt 并行，同窗口交替取最优）**6134 → 4106 ms ≈ 1.5x**（两轮独立测量
//! 1.369x / 1.493x）；`syntax=` 7 帧合计 421 → 376ms；`levels` 首帧 12.5MB → 10.1MB。
//! 验收：真素材 20 帧 vs dav1d **四条路径（默认 / 标量 / row-mt 顺序 / row-mt 并行）全 0 差**，
//! 且两两**逐字节相同**；13 条受控流；384 单测。
//!
//! #### 副产物：本机 8 线程**不如** 4 线程（别再重复试）
//!
//! `ME_THREADS` 扫描（row-mt 并行，36 帧）：1→5973、2→4678、**4→4301**、8→4678ms。
//! 本机 **4 物理核 / 8 逻辑核**，而并行回放的**有效并行度只够 ~8 路**（反对角线 `diag = 2*band+col`
//! 分层；1080p 只有 9 带 × 15 超块列 = 135 个作业，且"**同带左邻列**"也算了依赖 ⇒ 一条带内是链）。
//! worker 利用率：4 线程 **75.6%**、8 线程 **46.3%**（×2 相对物理核 ⇒ ~92%，物理核已满）。
//! ⇒ 再快只能**削关键路径 / 串行部分**（帧级流水，或去掉"同带左邻列"这个保守依赖），**不是加线程**。
//!
//! ### 第十九轮：并行回放的"同带左邻列"依赖改为**条件性**（2026-10-04 凌晨）
//!
//! 第十八轮之后，4 线程的 worker 利用率只有 **74.9%** —— 并行回放还有空等。根因是作业图里
//! 那条"**同带左邻列**"边（`deps[2]`）：它本来只为**帧内预测的左邻读取**（`intra::derive_edges`
//! 的 `LeftCol`）而画，但切作业时是**无条件**加上的，于是**一条带内的 15 个列作业串成一条链**，
//! 有效并行度被压到"反对角线上 ~8 个"。
//!
//! 而**纯帧间块根本不读当前帧的像素**：
//! * 预测全部来自参考帧；
//! * `warp` 的样本只从**邻居的 MV** 估计（`mv::MotionField::find_warp_samples` 的文档明说
//!   "从不读当前块"，而 MV 在语法阶段就填好了）；
//! * OBMC 同样只消费参考帧 + 邻居 MV；`intrabc` 是唯一例外，但它在切作业时就把整帧
//!   退回了顺序回放。
//!
//! ⇒ 判据 `reads_cur_frame(b) = !is_inter || (interintra && !no_interintra())`：
//! **整列都是纯帧间块时就不画那条边**。
//!
//! 实测（36 帧，同窗口交替 A/B）：
//!
//! | 线程 | 第四刀后 | 第十九轮后 | 增量 |
//! |---|---|---|---|
//! | 4 | 4947 ms | 4971 ms | **0.995x（无收益）** |
//! | 8 | 6010 ms | **5535 ms** | **1.085x** |
//!
//! **4 线程总时间没变，但内部确实变快了**：worker 利用率 **74.9% → 83.8%**、
//! 回放作用域 **28.3 → 23.7 ms**。4 线程下瓶颈已经转移到别处（串行的 `syntax` ≈ 15ms、
//! 并行的 `filters` ≈ 31ms），所以收益被掩盖 —— **这一刀是为更多物理核准备的**。
//!
//! 正确性：真素材 **60 帧**三路径（默认 / row-mt 顺序 / row-mt 并行）两两**逐字节相同**，
//! 且默认与 row-mt 并行各自 vs dav1d **0 差**。⚠️ `ME_TRACE_RACE=1` 探针 0 命中，
//! 但该探针**只覆盖帧内预测的读取路径**（`racemap::is_written` 只在 `intra.rs` 被调用），
//! 对帧间块是盲的 —— 这次的证据是逐字节。
//!
//! #### 顺带厘清"帧间缺口"
//!
//! 4 线程整轮 5083ms / 40 解码帧 = **127 ms/帧**，而 `PHASE` 求和只有 107.9 ms/帧，
//! 缺口 **19.2 ms/帧** —— 大概率是**落盘 IO**（36 帧 nv12 约 112 MB），不是解码开销。
//! 真实解码成本看 `PHASE`：稳态 **tiles 47.7 + filters 31.0 ≈ 83.9 ms/帧**。
//!
//! ### 第二十轮：record 阶段**直写 arena**（2026-10-04 凌晨）—— 语法再省 11%
//!
//! 第五刀之后重测：**row-mt 的语法阶段仍比纯语法贵 1.67x**（20.9 vs 12.6 ms/帧，
//! 同口径 `AV1_TRACE_SYNMS` vs `AV1_SYNTAX_ONLY`）—— 差额 **8.4ms/帧**就是"记录"。
//!
//! 根因是 record 阶段有**两次**拷贝：`coeffs` 先把系数写进 `TxScratch::levels`，
//! `push_txb` 再整段 `extend_from_slice` 进 arena。
//!
//! **修法**：新增 `RowMtJobs::reserve_levels(n)`（`resize` 预留并清零、返回下标）与
//! `push_txb_meta(job)`，让 `coeffs` **直接写 arena** 的那段切片 —— 两次并一次。
//! 借用上要绕开"`self.record`（`&'a mut RowMtJobs`）与 `self.coeffs(&mut self, …)`
//! 不能共存"：先 `let mut rec = self.record.take()`，写完再 `self.record = rec` 放回
//! （`out` 的生命周期在 `coeffs` 之后结束，NLL 允许 `rec` 随后移动）。
//!
//! 实测（4 线程，**同口径、同进程内计时**）：`syntax` **20.9 → 18.6 ms/帧（-11%）**；
//! 记录税从 8.4 降到 6.0 ms/帧。
//!
//! ⚠️ **整帧收益无法可靠测量**：本机噪声极大（同一二进制 5 轮 `elapsedMs` 波动 ±25%）。
//! 36 帧交替 A/B 给出 4 线程 1.056x / 8 线程 0.972x，改用中位数则是 1.15x / 1.02x ——
//! **连符号都不稳定**。用 100 帧的进程内 `PHASE` 求和对比（tiles 4134→3481 = -15.8%、
//! filters 2714→2378 = **-12.4%**）：`filters` 与本次改动**毫无关系**却"快了"12.4%，
//! 可见那是机器漂移；**扣掉漂移后 tiles 的真实收益约 3%**，与 `syntax` 的 -11% 量级自洽。
//! ⇒ **以后量 5% 以下的差异要用进程内指标（`PHASE` / `SYNMS`），别信 `elapsedMs`。**
//!
//! 正确性：真素材 **60 帧**四路径（默认 / 标量 / row-mt 顺序 / row-mt 并行）
//! 两两**逐字节相同**、各自 vs dav1d **0 差**；13 条受控流；384 单测。
//!
//! ### ❌ 本轮曾**论证后放弃**、随后被推翻：LR 竖直方向按档
//!
//! 当时的理由是"`box_filter` 的主体是末段的 `h × w × 9` 三位加权（与 h 成正比、无重复），
//! 竖直档只摊薄初始窗口与 per-call 开销 ⇒ < 1%；且 64 行档必跨 stripe"。
//! **两条都错**（见第二十一轮）：stripe 与恢复单元边界**同源于 `(lumaY + 8)` 的 64 倍数**，
//! 只要档从该边界起算就不跨；而且漏算了中间表 `fill(0)` 等三块大头。
//!
//! ### 第二十一轮：LR **竖直方向也按档**（2026-10-04）—— filters 再省 11.5%
//!
//! `restore_block` 原先水平按 `LR_CHUNK = 64` 一档，**竖直仍按 `MI_SIZE`**（亮度每 4 行、
//! 色度每 2 行重来一次）。让竖直也按 64 行一档的依据是**三条边界同源**：
//! `stripe_num = (lumaY + 8) / 64` 与 `unit_row = ((lumaY + 8) >> sub_y) >> log2(unit_size)`
//! （`unit_size ∈ {64,128,256}`）—— 只要档不跨 `(lumaY + 8)` 的 64 倍数，
//! `stripe_start_y` / `stripe_end_y` / `unit_row` / `rtype` 在档内全恒定。
//! `get_source_sample` 的钳位是逐样本语义 ⇒ 档的划分**不影响任何取值**（逐位不变）。
//!
//! **改法**：`restore_block` 多收 `chunk_rows`；`apply` 的 `y` 推进改为"到下一个
//! `64m − 8` 边界"（首档 56 行、之后 64 行）；⚠️ **并行切分点吸附到档边界**
//! （MI 行 `16m − 2`），否则一个档被切在 worker 交界处会误用前一个 `rtype`。
//! 缓冲上限随之上调（`SGR_AB_MAX` 400→4400、`SGR_F_MAX` 256→4096 等），
//! 亮度档峰值栈 ≈ 70 KB（macOS 子线程默认 512 KB，放得下）。
//!
//! 顺带删掉 `f0`/`f1`/`interm` 的**死 `fill(0)`** —— `box_filter` 的三条出口与
//! `wiener_filter` 的双重循环都会全量覆写，那几笔一帧要白写十几 MB。
//!
//! 实测（100 帧，4 线程，同窗口交替 A/B，只信 `PHASE`）：`Σfilters` **3870 → 3521
//! （−9.0%）**；再删死 `fill` 后 **3041 → 2693（−11.5%）**；`tiles` 全程不动。
//! 整帧 **75.9 → 72.7 ms/帧（−4.2%）**。真素材 60 帧四路径两两逐字节相同、各自 vs dav1d
//! **0 差**；13 条受控流（含两条 `unit_size` 的 LR 流）；384 单测。
//!
//! ### 第二十二轮：内核向量化 + 修白拷贝（2026-10-04）—— filters 再省 18%
//!
//! 第二十一轮之后重新采样（4 线程）：**MC ≈30%、LR ≈18%、deblock ≈11%**，
//! 外加 `bzero`/`memmove` 合计 ≈9%。这一轮把 LR 与 deblock 的大头向量化，并修掉三处白拷贝：
//!
//! * **`box_filter` 全面向量化**（采样里一直排第一）：末段的 3×3 加权 → `simd::sgr_final_8`
//!   （8 列独立）；A/B 表的窗口和 → `simd::sgr_ab_8`，把**水平滑动**（串行增量）
//!   换成**前缀和相减**以解开依赖。`a2` 的查表与 `z < 0` 分支仍是逐通道标量。
//!   ⚠️ 第一版在末段**多加了 `clip1`**，60 帧全错 —— 规范在 `box_filter` 只写 `F`，
//!   钳位在 `sgr_filter` 的最后混合里；被"`ME_NO_SIMD` 开/关逐字节"当场抓住。
//! * **去块 `lf_gate`**：一帧 33 万次 `loop_filter_edge` 里 92% 在 `isTxEdge` 就退出，
//!   把判定抽成 `#[inline(always)]` 让 `run_line` 热循环先内联判一次
