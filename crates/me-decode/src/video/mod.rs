//! ### 第四十五刀（2026-10-22）：反变换 8/10bit 走 8 路 i32 通道 —— **−10.1%**
//!
//! **重新采样（2026-10-22，1080p 真素材、单线程、主线程 7762 样本）**：
//! `vt_forward_1d` 已经是**整帧第一热点 14.5%**（旧数值 4.7% 来自另一份采样，
//! 这份素材的变换块更多）。根因是旧内核每条线只装 **4 个 i64**。
//!
//! **值域先行**（不然不敢换宽度）：
//!
//! ```text
//!   反量化钳位 |t| ≤ 2^(7+bd)
//!   蝴蝶和     ≤ 2^(7+bd)·2^13 = 2^(20+bd)
//!   8bit → 2^28   10bit → 2^30   12bit → 2^32 ✗
//! ```
//!
//! 所以 8/10bit 走 **8 路 i32**，12bit 仍 i64；4 宽/4 高的块凑不满 8 条线也走 i64。
//! 1D 内核保持**一份实现**（`simd.rs` 的 `vt_*` 用 `const I32: bool` 参数化，
//! 编译期折叠），新增 `vt_transpose8` 与两个 8 线驱动；i32 只在列趟之后扩回 i64。
//!
//! **实测**（同一二进制、`ME_NO_VT32=1` 关 i32；CPU 时间 / 100 帧 / 12 轮换序）：
//! 中位 **6.73s vs 7.49s，−10.1%（6/6 轮更快）**；采样里 `vt_forward_1d`
//! **14.5% → ~5%**。PGO 重训后旧/新 PGO 对照：**76.2 → 67.1 ms/帧（−12.1%，8/8）**。
//!
//! **验收**：24/60 帧与改前逐字节相同、`ME_NO_SIMD` / row-mt 顺序 / row-mt 并行
//! 逐字节相同、真素材 60 帧三平面与 dav1d 逐像素一致、`me-decode` 476 项全过、
//! 四个非本机架构编译通过。
//!
//! **下一刀的采样（同一次，新二进制）**：CDEF 合计 **~25%**（`cdef_filter`
//! 自身 9.6% + `cdef_pair16` 5.8% + `cdef_quad8` 3.7% + `dir_accum` 3.0% +
//! `apply` 3.2%），`deblock_edge4` 4.8%、`mc_shift_rows` 4.5%、`add_residual` 4.9%。
//!
//! ### 第四十六刀（2026-10-22）：残差回写前的预测块拷贝按行切片 —— **−4.7%**
//!
//! `add_residual` 每块先把预测从平面拷进连续的 `pred` 缓冲，原来是逐像素
//! `Plane::get(x, y)`：每次都要在 u8/u16 两种存储之间分支，还要做边界断言。
//! 改成**按平面分派一次** + 整行切片：u16 直接 `copy_from_slice`，u8 逐样本
//! 加宽到 u16（LLVM 可向量化）。输出逐字节相同。
//!
//! **实测**（cut45 PGO vs cut46 PGO，CPU 时间 / 100 帧 / 8 轮换序）：
//! 中位 **7.03s vs 6.705s，−4.7%（8/8 轮更快）**；按同口径折算约 **64 ms/帧**。
//! 绝对毫秒受机器负载影响，只信同窗口 A/B。
//!
//! **验收**：24/60 帧、`ME_NO_SIMD`、row-mt 并行逐字节相同；workspace
//! **1026 passed / 0 failed**。
//!
//! ### 第四十八刀（2026-10-23）：CDEF 右/下边界块也走 SIMD —— **约 −1~2%**
//!
//! 采样里 CDEF 的 `apply` 闭包自身是最大单项（874 样本 / 主线程），反汇编定位到
//! `+8055/+8142` 正是**标量候选循环**。计数（临时插桩）显示：标量只占
//! `cdef_filter` 调用的 **2.5%**（约 2214/90000），但每块要逐像素算 20 个候选、
//! 每个候选都做边界检查，耗时约占整帧 **10%** —— 全是帧右/下边界块。
//!
//! **改法**：把 SIMD 的 `interior` 条件放宽到右/下边界块（只保留
//! `x0>=2 && y0>=2` 与平面缓冲可寻址）。SIMD 内核会读到平面 padding，
//! 越界候选只污染最右/最下 1~2 行/列的**输出**；随后只对这两条边带
//! （`x_border = coded_w-2-x0`、`y_border = coded_h-2-y0`）用标量重算。
//! 左/上边界仍整套标量（平面没有负向 padding）。`ME_NO_CDEF_EDGE=1` 可回旧行为。
//!
//! **实测**（同一二进制、8 轮换序，CPU 时间 / 100 帧）：中位 **7.43s vs
//! 7.585s，−2.0%（7/8 轮更快）**；PGO 重训后两版对照 −0.7%（7/8），同一二进制
//! 复测 −1.2%（4/6）⇒ **保守记约 −1~2%**；按同口径折算约 **63~64 ms/帧**。
//!
//! **验收**：1920 宽真素材 24/60 帧逐字节相同、`ME_NO_SIMD` / row-mt 并行
//! 逐字节相同；**646 宽（非 8 倍数）**素材的边界 SIMD 与旧标量路径逐字节相同
//! （与 dav1d 的差异仍是已知的右边缘残差）；CDEF 6 项单测通过。
//! ⚠️ 先试过"两个阈值都为 0 就早退"，但计数器显示这条流 **0 次命中**
//! （A/B 的 ~1% 是噪声），已撤掉。
//!
//! ### 第四十九刀（2026-10-23）：去块 `filter_strength` 的常量快路径 —— **约 −0.7%**
//!
//! `filter_strength` 每条边都要从 `grid` 随机读 `seg_ids` / `ref_frames` /
//! `y_modes` / `delta_lfs`，再走一遍分段特征与 ref/mode delta；`lvl == 0` 时
//! 还要为另一侧再调一次。而**没有 delta_lf、没有 ref/mode delta、分段也不调
//! LF** 的帧里，`lvl` 只跟 `(plane, pass)` 有关 —— 真素材正是这一档
//! （`AV1_TRACE_DBL` 可见 `delta_enabled=false`、`delta_lf_present=false`、
//! `seg_enabled=false`）。
//!
//! 现在先判这三个条件，命中就直接返回 `lf_derive(lf, lf.level[i])` 的常量；
//! 不读 `grid`、不算模式。`limit/blimit/thresh` 的推导抽成 `lf_derive` 共用。
//!
//! **实测**（同一二进制、8 轮换序，CPU 时间 / 100 帧）：中位 **7.085s vs
//! 7.135s，约 −0.7%（7/8 轮更快）**。收益不大，但这条路径的随机读确实整段省掉。
//! 顺带试过 `nv12_frame` 去掉 `vec![0u8]` 清零，A/B 持平（bzero 不来自它，
//! 大块分配走的是惰性零页）⇒ 已回退。
//!
//! ### 第五十刀（2026-10-23）：整数相位 MC 补 4 宽尾段 —— **约 −0.7%**
//!
//! `mc_shift_rows` 只按 8 宽跑，`n = 4`（色度/窄块）与 12/20 宽块的尾部全落
//! 标量 `round2_i32` 循环。补一段 4 宽内核：`loadl_epi64` 载 4 个 u16 →
//! `cvtepu16_epi32` 零扩展 → 同一个 `post_round` 移位 → 128 位存 4 个 i32。
//! 4 宽与 12/20 宽的块因此整块走 SIMD，标量尾消失。
//!
//! **实测**（同一二进制、8 轮换序，CPU 时间 / 100 帧）：中位 **6.81s vs
//! 6.855s，约 −0.7%（5/8 轮更快）**；与第四十九刀同量级，属"严格少做"的小刀。
//!
//! ### 第五十一刀（2026-10-23）：i32 残差不再扩宽，直接加回预测 —— **−2.7%**
//!
//! 第四十五刀让 8/10bit 的反变换在 i32 里跑完之后，`inverse_transform_2d_into`
//! 又把 `w·h` 个 i32 **逐个扩宽成 i64** 写进 `residual`，`inverse_transform_add`
//! 再逐像素读回来转 i32 加预测 —— 一写一读全是白费，且让最终加法只能标量做。
//!
//! 现在 `inverse_transform_2d_into` 返回 `bool`（true = 结果在 `residual32`），
//! `inverse_transform_add` 直接读 i32 残差：
//! 非翻转（绝大多数 DCT_DCT）按行取 `pred`/`res` 连续切片，内层
//! `clip1(p + r)` 可被 LLVM 向量化；翻转类型走同一份带 flip 映射的标量循环。
//! 12bit 与 4 宽/4 高的块仍走 i64 路径（返回 false）。`debug_inverse_only`
//! 在自己的诊断副本上转回 i64，对外契约不变。
//!
//! **实测**（同一二进制、8 轮换序，CPU 时间 / 100 帧）：中位 **6.07s vs
//! 6.24s，−2.7%（7/8 轮更快）** —— 是第四十六刀之后最大的一刀。
//!
//! #### 第五十三刀（2026-10-23）：CDEF 按 64×64 组批处理 + 四行内核 —— **−4.8%**
//!
//! 隔离开关先说清水位：`AV1_NO_CDEF=1` 整帧 **−23.9%**（6/6 轮）⇒ CDEF ≈15 ms/帧，
//! 是最大单项；而采样里 `apply` 的驱动闭包和三个内核几乎一样贵 —— 每块 3 次
//! `cdef_filter` 都要重算 `interior`/`coded_w`/边界条带/候选偏移表。
//!
//! * [`cdef::apply`] 改成**按 64×64 组**走：组级取一次 `cdef_idx` 与强度
//!   （`cdef_idx < 0` 一次跳过 64 块），内点块直接进 `cdef_group_fast`
//!   （无边界判定/无条带补算），帧边块（约 1%）回落 `cdef_block`；
//!   帧底不满的那半行也按组跑、只跑还在帧里的块行。
//! * 两个平面强度都为 0 的块是恒等变换（`acc=0`、`Clip3(min,max,cur)=cur`），
//!   连方向都不算。
//! * 新内核 `cdef_pair16x4`：**四行一组**（两个 YMM、两条独立依赖链），
//!   微基准两行 286 ns → 四行 263 ns（1.09x）；单测对 8 方向 × 3 种块形 ×
//!   3 组强度与两行版**逐字节**对拍。
//!
//! ⚠️ 第一版组循环忘了把行迭代器推过组内的 8 个块行 ⇒ 每块被滤了最多 8 遍，
//! **输出仍逐字节相同**（CDEF 读 `CurrFrame`、写克隆，重复滤波幂等），
//! 只有计时暴露 **+15.3%**。`md5` 只能证明"没算错"，不能证明"没多算"。
//!
//! 实测：同二进制 A/B **−4.8%（8/8 轮）**；PGO 前后 **61.8 → 59.3 ms/帧
//! （−4.2%，6/6 轮；另一窗口 10 轮 −5.2%）**。验收：24/60 帧逐字节、`ME_NO_SIMD`
//! 与 row-mt 逐字节、60 帧与 dav1d 逐像素、全测试 0 失败。下一刀：方向搜索
//! （`dir_accum` 的 512 B 栈 partial + 每行 6 次重叠 RMW，≈4 ms/帧）。
//!
//! #### 第五十四刀（2026-10-23）：CDEF 边界块候选掩码 + 方向搜索寄存器化
//!
//! * **边界块**（帧四周约 2.3% 的块，`cdef_filter` 采样 4.6%）：原来每个像素的
//!   12 个候选都走 `cdef_get_at`（坐标换算 + 越界比较 + `Plane::get` 分派）。
//!   现在候选 `(dx,dy)`/线性偏移每块算一次，**有效性压成"列掩码 & 行掩码"**
//!   （规范只要求落在帧的 4×4 网格内），内点全 1 掩码走无分支快路径。
//! * **方向搜索**（`dir_accum`+`cdef_direction` 采样 6.6% → **2.8%**）：旧的
//!   512 B 栈 partial 每行 6 次**重叠**读-加-写（store-forwarding 必失败）。
//!   新 `simd::cdef_direction_avx2` 每个方向只开 2 个 XMM 累加器，用
//!   `pshufb` 把一行搬到 `[base, base+8)`，代价用 `pmaddwd` 求对称位置的
//!   平方和、`vpmulld` 乘 Div 表 —— 全程寄存器、i16 中间量。
//!   单测 `cdef_direction_avx2_matches_scalar_bit_for_bit` 对 8/10/12bit ×
//!   三种数据 × 5 个位置与标量 `(yDir, var)` 逐位对拍。
//!
//! 同二进制 A/B（方向 SIMD vs 纯标量）**−10.7%（10/10 轮）**；`cdef_filter`
//! 采样 4.6% → 2.1%。**PGO 版对上一版 PGO：60.07 → 56.61 ms/帧（−5.7%，10/10 轮）**。
//! 验收：24/60 帧逐字节、`ME_NO_SIMD`/row-mt 逐字节、dav1d 60 帧逐像素、
//! 全测试 0 失败。CDEF 仍是最大单项（约 10 ms/帧），下一位是色度
//! `cdef_quad8` 与亮度 `cdef_pair16x4` 的载入/存回。
//!
//! #### 第五十五/五十六刀（2026-10-23）：残差就地写回 + NV12 UV 交错 + 整像素预测直写平面
//!
//! * **残差就地**：`add_residual` 原来先把预测从帧平面拷进 `pred` 缓冲，反变换加法
//!   再读它。预测本来就在平面里 ⇒ 新增
//!   [`transform::inverse_transform_add_in_place`]，加法循环直接读平面（翻转时
//!   读写的仍是同一个 `(yy, xx)`）。同二进制 A/B **−0.9%（7/10 轮）**。
//! * **NV12 4:2:0 UV 交错**：每对样本两次单字节写 → 每 8 对一次
//!   `packusw`+`punpcklbw`（输出逐字节相同）。
//! * **整像素单参考预测直写平面**：非复合时 `InterRound0+InterRound1 = 14`
//!   ⇒ `post_round = 0`，整像素预测值就是源样本；`store_row_clamped` 只做
//!   `clamp`。于是 `predict_inter` 在"单参考/整像素/非复合/无 interintra/无 OBMC"
//!   时用 [`inter::store_integer_pred`] 直接按行拷进帧平面，省掉 i32 缓冲的
//!   4 B 写 + 4 B 读与逐行 store。同二进制 A/B **−1.2%（8/10 轮）**。
//!
//! 三处合起来 PGO 终测 **58.80 → 57.58 ms/帧（−2.2%，10/10 轮）**；
//! 24/60 帧逐字节、`ME_NO_SIMD`/row-mt 逐字节、dav1d 60 帧逐像素、
//! 全量测试 **1028 passed / 0 failed**。
//!
//! #### 第五十七/五十八刀（2026-10-23）：直写行拷贝内联 + 零 MV 投影快路径
//!
//! * 直写平面的 `copy_from_slice` 对运行时行长会编译成 `memmove` 调用；按块宽
//!   （2/4/8/16/32 个 u16）内联成 32/64/128 位未对齐读写：同二进制 A/B
//!   **−0.9%（7/10 轮）**。
//! * `mv::project_frame` 的零 MV 格子：`project_k(0,k)=0` 恒成立 ⇒ 7 个目标帧的
//!   投影全是 `(0,0)`、落点相同。快路径只算一次 `block_position` 再整段写零，
//!   省掉 16 次 i64 乘法：同二进制 A/B **−1.4%（8/10 轮）**。
//!
//! 五刀（残差就地、NV12 交错、整像素直写、行拷贝、零 MV）合计 PGO 终测
//! **56.40 → 53.90 ms/帧（−5.2%，9/10 轮）**；全量测试 1028 passed / 0 failed。
//!
//! #### 第五十九刀（2026-10-23）：CDEF 左/上边界块的"位移 SIMD"
//!
//! 帧左/上边界没有负向 padding，这类块原来整块走标量。现在把内核起点右/下移
//! 2 个样本再跑 SIMD，多写的 2 列/行**先从 `CurrFrame` 还原**（相邻块可能是
//! skip、不会覆盖回来），再用掩码标量补算。同二进制 **−0.6%（6/10）**，
//! PGO 版对上一版 **52.79 → 52.17 ms/帧（−1.0%，8/10）**。
//! ⚠️ 忘了还原块外写入会让 skip 邻块留下邻块的滤波值（60 帧对拍第 16 帧抓到）。
//!
//! #### 第六十一刀（2026-10-23）：LR 的 `RESTORE_NONE` 平面零拷贝
//!
//! 环路恢复对不滤波的平面原来整平面 `copy_from_slice`（1080p 色度约 2.5 MB/帧）。
//! 两份源本来就是按值传入的 ⇒ 直接把源平面 `mem::swap` 进输出帧（换出来的新平面
//! 回池），输出逐字节不变。PGO 版 **59.23 → 58.89 ms/帧（−0.2%，5/6 轮）**。
//!
//! #### 第六十四刀（2026-10-23）：NV12 输出缓冲池化 —— −2.1%（PGO −1.6%）
//!
//! `nv12_frame` 每帧 `vec![0u8; w*h*3/2]`（1080p 3.1 MB）分配+清零+释放，
//! 而这条路径每个字节都会被写满 ⇒ 清零纯属白写。现在 `VideoFrame` 在 `Drop`
//! 里把 `nv12` 还给 u8 缓冲池，`nv12_frame` 优先取池。
//! 同二进制 **−2.1%（7/8）**、PGO **−1.6%（6/8）**。
//! 收益远大于"3 MB 带宽 ≈0.3 ms"的估算（实测 ~1.2 ms）——省的是每帧的
//! mmap + 缺页 + 释放，**估算不能代替实测**。
//!
//! #### 第六十五刀（2026-10-23）：`CurrFrame::decoded` 网格池化
//!
//! `decoded`（4×4 已重建标记，1080p ≈ 0.19 MB/帧）每帧要建三份（重建 / CDEF 克隆 /
//! LR 输出）⇒ 约 0.6 MB 的分配+清零/拷贝。沿用 u8 池：`new` 取池后 `fill(0)`、
//! 手写 `Clone` 取池后拷贝、`Drop` 归还。同二进制 **−1.0%（6/8）**、
//! PGO **−0.4%（5/8）**。全量测试 1028 passed。
//!
//! #### 第六十六刀（否定，2026-10-23）：`BlockGrid.mvs` 跳过逐帧清零
//!
//! 2 MB/帧的填零，改成 `ensure_len` 后 100 帧对拍、dav1d、测试全过（同二进制 −1.2%），
//! 但 `BlockGrid` 顶部**明确把 `mvs` 列为"必须保留初值"**（"门与写同源"的依赖链
//! 太隐晦）。单流通过不足以推翻这条约定 ⇒ **已回退**。
//!
//! 硬解那一路在 [`crate::macos`]：AV1 会**先试硬解**（M3+ 成功），失败才落到这里。
//! 这不是"回退到浏览器"，而是同一个引擎里的两个后端（DEVELOPMENT.md 的"硬解优先、自研
//! 软解兜底"）。

