//! **刀 1：横向 MC 的"收尾"11 条 → 2 条（`pmulhrsw` + `paddw`）。**
//! `mc_horiz16_8bpc` / `mc_horiz8_8bpc` / `mc_horiz16_u8` 与
//! `mc_horiz_rows_8bpc` 的 16 宽内联段，末尾都是
//! "`cvtepi16_epi32` ×2 → `add_epi32` 抵消偏置 ×2 → `rnd` ×2（各 `add`+`srai`）
//! → `packs_epi32` → `permute4x64`" = **11 条**。而带偏置累加的 `acc = Σ − 2¹⁴`
