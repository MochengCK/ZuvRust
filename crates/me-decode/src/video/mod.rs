//! * **`vt_srai_c`：i64 算术右移 5 条 → 3 条。** AVX2 没有 `srai_epi64`；
//!   老写法是"复制符号位 → 逻辑右移 → 或回去"（`shuffle_epi32` + `sllv` + `srlv` + `or`）。
//!   而**一个 i64 就是两个 i32**、32 位**有** `srai_epi32` ⇒
//!   `blend_epi32::<0xAA>(srli_epi64::<N>(v), srai_epi32::<N>(v))`
//!   （低半取前者、高半取后者）。配 `vt_round2_c::<N, SHL>` 换掉所有**常量移位**落点：
//!   蝴蝶 ×2（12）、ADST4（12）、identity 预缩放（12）、1:2 预缩放（12）、
//!   行写回（`row_shift ∈ {0,1,2}`）、列写回（`col_shift ∈ {0,4}`）。
//! * **`cos128`/`sin128`：四象限分支 → 256 项直查表**（`COS128_FULL` 编译期按同一
//!   式子求值；`sin128(a) = COS128_FULL[(a - 64) & 255]`）。每个蝴蝶 2 次调用。
//! * **`brev`：逐位循环 → 64 项表**（`BREV6[x & 63] >> (6 - numBits)`）——
//!   `vt_dct_permute` 对**每个元素**都要调一次（32 点 = 32 次、64 点 = 64 次）。
