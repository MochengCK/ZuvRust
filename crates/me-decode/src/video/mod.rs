//! **每个采样要重建 4~6 次 `MediaInfo`** —— 每次都是 `Vec<Track>` + 每轨
//! `codec`/`extradata`/`language` 的克隆，**外加一次 `stat(2)` 系统调用**
//! （`GrowingFileSource::len()` 走的是 `std::fs::metadata(路径)`，要重新做一遍
//! VFS 路径解析）。而这一整串**只需要一样东西**：轨道时基
//! （`Timebase { ticks_per_second }`）。
//!
//! ### 改法（两处，都很小）
//!
//! 1. `Player` 加一个 `OnceLock<Vec<(u32, Timebase)>>` **时基快照**，
//!    `span_of` / `pts_us_of` / `refresh_buffer_window` / `next_packet` 全走它。
//!    **只快照时基**，不碰 `frame_rate` 这类"后续 `moof` 解析完可能变化"的字段；
//!    判据是**语义逐位不变**（找不到轨道时同样按 90kHz 兜底）。
//!    `Player::info()`（公开 API）保持"每次都新算"，对外行为不变。
//! 2. `GrowingFileSource::current_len()` 从"按路径 `stat`"改成**用缓存的读句柄
//!    `fstat`**：省掉路径解析，而且长度与读到的内容来自**同一个 inode**
//!    （路径上的文件被换掉时不会出现"长度按新文件、数据按旧 fd"）。句柄没开时
//!    退回原路。
//!
//! ### 刀 2：`mc_vertical_pass` 的**变量除数除法**
//!
//! `let rows = intermediate.len() / wu;` —— 每个预测块一次变量除数的整数除法
//! （~25 周期），1080p 一帧 3 万多个块 ⇒ 约 0.5 ms/帧。调用方本来就知道这个值
//! （`interp_h`），直接传进来即可。
//!
//! ⚠️ **方法论**：这条是靠"把热文件里所有**非常量**除法扫一遍"找出来的 ——
//! 全仓库扫描只找出**这一处**真正的热除法（其余都是常量除数，会被折成移位/
//! 乘法倒数）。**热路径上看见 `/` 永远是可疑的。**
//!
//! ### 实测
//!
//! | 口径 | 轮次 / 帧 | 配对中位 | 同向 |
//! |---|---|---|---|
//! | 刀 1（时基快照 + fstat）单独 | 20 轮 / 100 帧 | **−1.7%** | **15/20** |
//! | 两刀合计 | 20 轮 / 100 帧 | −1.6% | 13/20 |
//!
//! 两次窗口的负载不同（第一次 load 8~10，第二次 8/15/24）—— 合计那一轮窗口更脏，
//! 13/20 与 15/20 的差别主要来自窗口，不是刀 2 的贡献。
//!
//! ### 验收
//!
//! 24 帧与改前**逐字节相同**、**7 条受控流 0 差**、真素材 60 帧三平面与 dav1d
//! **逐像素一致**、`ME_NO_SIMD` 开/关**逐字节相同**、row-mt 串/并行**逐字节相同**、
//! **workspace 942 passed / 0 failed**、clippy **0 error**、
//! aarch64-apple-darwin `cargo check` **0 error**。
//!
//! #### 第三十九轮（2026-10-06）：去块 **8 线合并** —— 一次完整的否定实验（净 +0.3%，已回退）
//!
//! 详细账在 `内部优化记录` 第二十二节。这里是结论。
//!
//! ### 设计（**推理成立，代码也已逐位验证**）
//!
//! 去块是三个环路滤波里最大的一块（`AV1_NO_DEBLOCK` 隔离开关 = **−10.3%**），
//! 而内核一次只处理 `MI_SIZE = 4` 条线。两个洞察让它看起来必然能翻倍：
//!
//! 1. **相邻的两条边互不重叠**：滤波方向**垂直于**边（pass 0 的一条边只碰 4 个
//!    连续**行**、相邻边碰另外 4 行）⇒ 可以合批、行内顺序无关；
//! 2. **换 i16 通道**就能把 8 条线塞进同一个 `__m128i` ⇒ 窗口 `v[]` 的**寄存器
//!    占用与 4 × i32 完全相同**，掩码/滤波器的**向量指令条数不变**。
//!
//! 内核写了、也被 `deblock_edge8_matches_edge4_bit_for_bit`（8/10bit × plane{0,1}
//! × `filter_size`{4,8} × 3 组阈值 × 3 类数据 × 整块缓冲）证明**与 4 线版逐位等价**
//! —— 那条单测还在第一版里当场抓到 `dbl_store8_v` 漏了 `x` 偏移。
//!
//! ### ⭐ 三种驱动的实测（**这一轮的真正产出**）
//!
//! | # | 驱动写法 | 配对中位 | 同向 |
//! |---|---|---|---|
//! | ① | 主行顺手把配对边的参数也算出来比一比，真合并 | **+3.4%** | 2/16（更慢）|
//! | ② | **永不合并**、但两条边参数都算完（分离实验）| **+5.7%** | 1/16（更慢）|
//! | ③ | 两条线各自 `collect_edges`（参数各算一遍）+ 双指针归并 | **+0.3%** | 10/20（打平）|
//!
//! * **① − ② = −2.3 个点** ⇒ 内核确实在赚；
//! * **③ ≈ 0** ⇒ 把"参数算两遍"修掉之后，**内核那 2.3 个点也没了**；
//! * 唯一自洽的解释：**8bit/u16 下 8 线内核的算术并没有按线数摊薄** ——
//!   掩码/滤波器的向量指令条数本来就和通道数无关，翻倍的是产出，而
//!   **load/store 侧更贵**（8×8 u16 转置多 24 条 shuffle + 8 行各一次 16B 存）。
//!   ⇒ **去块内核不是 ALU 受限，是载入/存回受限。**
//!
//! ### 回退，以及顺序
//!
//! 净 +0.3%（10/20）落在噪声里 ⇒ 按纪律回退驱动接线并**删除**内核与单测
//! （8bit/u16 下前提不成立；u8 路线下要按 u8 读重写，留着只是死代码）。
//!
//! ⚠️ **`ME_PLANE_U8` 必须先做**：u8 存储下 16 条线能塞进一个 `__m256i`
//! （`vpmovzxbw`：16 字节 → 16 个 i16），**这时 load/store 侧才会跟着线数摊薄**。
//! 本轮数值就是这条顺序的证据。
//!
//! ### 两条方法论（详见交接文档）
//!
//! * **"顺手也算一下隔壁"的写法要先问"隔壁自己会不会再算一遍"** —— ① 看着自然，
//!   实际让每条边的参数计算翻倍（+5.7% 全是它）。
//! * **分离实验 > 开关实验**：② 把"内核收益"与"驱动开销"分开量了；没有它，
//!   一次 +3.4% 的回归就会被误判成"8 线内核不行"。
//!
//! #### 第四十轮（2026-10-06）：`warp::block_warp` 的 AVX2 化 —— **−3.1%**（32 轮 27 轮更快）
//!
//! 这一轮的猎物是**全仓库唯一一个"完全没碰过 SIMD"的热内核**：`warp.rs` 545 行，
//! `simd` / `avx2` / `target_feature` 三个词的出现次数都是 **0**，而 `block_warp`
//! 在采样里占 **2.7%**。
//!
//! ### 为什么它值得重写
//!
//! 每个 8×8 子块：横向 15 行 × 8 列、纵向 8 行 × 8 列，**每个输出各 8 个抽头**，
//! 而 `Warped_Filters` 是按亚像素相位查表的 ⇒ **同一行里 8 个输出的滤波器互不
//! 相同**。合计 **1472 次 `imul` + 1472 次 `add`**；`imul` 在这台机器上吞吐就是
//! **1 条/周期** ⇒ 光乘法就 ~1500 周期/块。另外每块还有 **184 次 `filter_row()`**
//! （`usize::try_from` + `.filter()` + `Result`）。
//!
//! ### 两个关键事实（先把值域算清楚，再动手）
//!
//! 1. `WARPED_FILTERS` 的抽头 ∈ `[-127, 127]`、**`Σ|c| ≤ 222`**（193 行全扫过一遍）
//!    ⇒ `i16` 装得下，而 `i16` 正是 `vpmaddwd` 要求的宽度（一次 16 通道）。
//!    一个输出的 8 个乘积和 ≤ `4095·222 = 908,890` ⇒ `i32` 装得下。
//! 2. 中间量 = `Round2(Σ c·x, r0)` ≤ `4095·222 >> r0`：**8bit 7076、10bit 28388**
//!    ⇒ 装得进 `i16`；**12bit 会到 113612，装不下** ⇒ `bit_depth > 10` 必须回落标量。
//!
//! ### 怎么让 8 个**不同**的滤波器共享一次 `pmaddwd`
//!
//! 输出 `j` 的源窗口是 `src[j .. j+8]` —— **相邻输出只差一个样本**。于是：
//!
//! * 把两个输出 `(2p, 2p+1)` 的 8 抽头系数放进 256 位寄存器的两个 128 位道
//!   （`_mm256_set_m128i`）；
//! * 源窗口用 `_mm256_loadu2_m128i(src + 2p + 1, src + 2p)` **一次载入两个错开
//!   一个样本的窗口**；
//! * `madd` 出的 8 个 `i32` 正好是「低道 4 个部分和 = 输出 `2p`、高道 4 个 =
//!   输出 `2p+1`」；4 组 `madd`（8 个输出）+ **3 次 `hadd`** 把每组的 4 个部分和
//!   收成 1 个：
//!
//! ```text
//!   t01 = hadd(m0, m1)   t23 = hadd(m2, m3)   u = hadd(t01, t23)
//!   u = [ s0, s2, s4, s6,    s1, s3, s5, s7 ]     ← 偶数输出在低道、奇数在高道
//! ```
//!
//! * 取整在向量里做（`add` + `sra`），再 `packs_epi32` 收成 `i16`、`pshufb` 摆回
//!   `[s0..s7]`，**一次 16 字节存进中间缓冲**。
//!
//! ### 纵向：先把中间缓冲转置
//!
//! 纵向第 `i1v` 个输出用 `inter[i1v + k][i2v]` —— 沿**行**方向取抽头，在行主序里
//! 跨 `stride`。把 15×8 的中间缓冲转置成 `interT[列][行]`（**两个 8×8 `i16` 转置**，
//! 与去块那次的 `dbl_transpose8` 同一套 24 条 shuffle）之后，每一列的 8 个抽头就
//! **连续**了 ⇒ 纵向原样复用横向那一整套。
//!
//! ### `offs` 越界怎么处理（不能 panic）
//!
//! 标量路径用 `filter_row()` **每次**返回 `Result`，越界给的是精确报错。SIMD 里
//! **不能靠下标 panic**（那是崩溃，不是报错）。做法：`sx`/`sy` 对 `(i1, i2)` 是
//! **线性**的 ⇒ 极值必在角点，一次算出 `offs` 的 `[lo, hi]` 范围，越界就返回
//! **`Ok(false)`**（"这条流不能走 SIMD"），调用方回落标量、由它给出原来那条报错。
//!
//! ### 结果
//!
//! | 口径 | 轮次 / 帧 | 配对中位 | 同向 |
//! |---|---|---|---|
//! | CPU 时间交替 A/B | **32 轮 / 100 帧** | **−3.1%** | **27/32** |
//!
//! ### 验收（全绿）
//!
//! 24 帧与改前**逐字节相同**、**7 条受控流 0 差**、真素材 60 帧三平面与 dav1d
//! **逐像素一致**、**`ME_NO_SIMD` 开/关逐字节相同**（新 SIMD 路径的关键判据）、
//! row-mt 串/并行**逐字节相同**、clippy **0 error**、aarch64 `cargo check` **0 error**、
//! **workspace 943 passed / 0 failed**（新增 `warp_simd_matches_scalar_bit_for_bit`）。
//!
//! ### ⚠️ 一条方法论：**"一次就过"必须排除空跑**
//!
//! 那条逐位对拍单测**第一次跑就绿了**。这正是最该怀疑的时候 —— 如果 6 组
//! `warpParams` **全都不过** `setup_shear` 的 `warpValid`，循环体一次都不执行，
//! 测试会**假绿**（自己跟自己比当然相等）。所以加了两个计数断言：
//! `shears_ok >= 3`（参数集至少过了 3 组）与 `ran >= 40`（真的对拍了 40 组以上），
//! 并且每组都断言 SIMD **返回了 `Ok(true)`**（`Ok(false)` = 回落 = 又在自己比自己）。
//!
//! ### 顺手把结构理开
//!
//! 原来的 `block_warp` 现在拆成**分派器** + [`block_warp_scalar`]：后者既是回落
//! 路径，也是那条对拍单测的**参照系**（这样"SIMD 与标量逐位相同"是可以在单测里
//! 直接验的，不用靠外部参考）。
//!
//! ### 同时重新量了一遍全局（记下来，省得下次重查）
