//! ⚠️ **第一版写错了**：把 `(v << (64-N)) >> (64-N)` 当成算术右移 —— 那是**逻辑**右移
//! （左移把符号位丢出 64 位），**负数全错**。是 `ME_THREADS=1` 的**逐字节对拍在第一次
//! 构建后就抓出来的**。修完补了 `vt_srai_const_matches_arithmetic_shift`：参照系用
//! **Rust 自己的 `i64 >> n`**，对 `N ∈ 1..=31` × 含 `i64::MIN/MAX/-1/0/±2^k` 的输入
//! 逐值对拍 —— 比"跟另一份 SIMD 实现对拍"强，**不会两个都错还互相印证**。
//!
//! **实测**：`vt_forward_1d` **6.5% → 4.5%（−31%）**；整帧（14 轮交替，CPU 时间）
//! **配对中位 −3.0%**（10.16 → 9.86 s，14 轮里 13 轮更快）。
//!
//! ⚠️ 同一批里 `vt_srai_c` **单独**那版在 10 轮窗口里测不出（配对中位 +0.9%，
