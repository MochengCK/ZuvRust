//! `vt_forward_1d` 是第 3 大热点（6.5%）。**通道必须留在 i64**（2026-10-02 的插桩实测：
//! "乘法输入 `|t| ≤ 2^19.5`，**积与和要到 ~2^32**"）⇒ "i64→i32 换 8 路"不通，
//! 只能逐条指令省。三刀：
