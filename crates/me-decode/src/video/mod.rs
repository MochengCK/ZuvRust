//! ② `cdef_direction` 每 64×64 只调一次 ⇒ 方向搜索不是 CDEF 的成本，
//! 成本在 `cdef_filter` 的逐像素抽头 + `cdef_block8` 的 u16 数据：
//! **filters 是"半标量 + u16"，dav1d 是"全 SIMD + u8"。**
//!
//! #### 第二十七轮（2026-10-04）：CDEF 内核换 **i16 通道 + 两行打包** —— 内核 **2.24x**
//!
//! 先把目标与水位重新量准（本机 load ≈ 5~6 的窗口）：
//!
//! | | 单线程 |
//! |---|---|
//! | **dav1d**（PyAV，`thread_count=1` + `thread_type="NONE"`）| **11.6 ms/帧** |
//! | 我们（`tiles 28.5 + filters 14.4 + setup 4.4 + out 1.3`）| **≈ 48.7 ms/帧**（好窗口 38.6）|
//!
//! ⇒ **4.2x**（目标 33 ms ⇒ 差 1.48x）。采样（12 s 单线程）里 CDEF 是 filters 里最大的一块：
//! `cdef_block8` **5.2%** + `cdef::apply` 闭包 3.5% + `cdef_filter` 3.3% ≈ **12%**。
//!
//! **改法**：`simd::cdef_block8`（i32 通道、一次一行 8 像素）→ **`simd::cdef_pair16`**
//! （**i16 通道、一次两行 × 8 列 = 16 通道**，低 128 位 = 行 `r`、高 128 位 = 行 `r+1`）。
//! 两件事叠起来：① 通道数 8 → 16；② 每个候选从"128 位载入 + `cvtepu16_epi32` 零扩展"
//! 变成"两次 128 位载入 + 一次 `_mm256_set_m128i`"。
//!
//! **i16 装得下的论证**（12 位最坏，8 位只会更小）：样本 ≤ 4095、`diff`/`mag` ≤ 4095、
//! 阈值 `pri/sec_strength << coeff_shift` ≤ **240**、`constrain` 结果 ≤ 240、
//! `Σ_{12} tap·val`（`tap ≤ 4`）≤ **11520**、`cur + ((8 + acc - adjust) >> 4)` ⊆ [-719, 4815]
//! —— 全部远在 i16 内。新单测 `cdef_pair16_matches_scalar_bit_for_bit` 覆盖
//! 8×8 亮度 / 4×4 色度 / **奇数行**（最后一行只算一次、只写一次）× 5 组阈值
//! （含 240 的最坏量级）。
//!
//! **顺带砍掉同一段热路径上的两处白活**：
//!
//! * `cdef_filter` 里 `let mut out = [0i16; 64]` 是**每次调用**一次 128 字节清零；
//!   1080p 一帧 3 平面 × (1920/8)×(1080/8) = 32400 块 ⇒ **~12 MB/帧的白写**。
//!   改成**每个 CDEF worker 一份、跨块复用**的 `scratch`（`apply` → `cdef_block` →
//!   `cdef_filter` 串下去）。
//! * `RowsSink::set_row_i16` 从"逐样本取值/比较/截断/存"变成**一次 `memcpy`**：
//!   内核输出已经过 `Clip3(mn, mx, ·)`（`mn`/`mx` 都是合法样本）⇒ 必在 `[0, 2^bd)` 内
//!   （debug 构建里有断言兜着）。CDEF 每帧要写 ~78 万行 × 8 个样本。
//!
//! **实测**：
//!
//! * **内核级（同进程交替的微基准 —— 本轮新增 `#[ignore]` 的 `bench_cdef_kernels`）**：
//!   8×8 亮度块 **448.6 → 199.9 ns ⇒ 2.24x**。
//! * **帧缓冲池：上限从「8 块」改成「96 MB」**（`pool.rs`）。8 块在 1080p 下只装得下
//!   3~5 块工作缓冲（luma ≈ 4.5 MB、chroma ≈ 1.2 MB），而稳态活着的缓冲超过 20 块
//!   （参考帧槽 + 本帧的解码帧 / CDEF 帧 / LR 输出）⇒ 池每帧都在 miss，
//!   `vec![0u16; n]` 重走 mmap，**每个平面第一页都要缺页中断**。
//!   ⚠️ **这一条是本轮最有用的一招：改用"确定性计数"来量**（新增 `AV1_TRACE_POOL=1`
//!   打印命中/落空 + 池内字节，另加 `ME_POOL_MAX_BYTES` 旋钮）—— 墙钟测不出来，
//!   命中率却一字不差：

//!   | 池上限 | 命中率 | 稳态落空 |
//!   |---|---|---|
//!   | 1 MB | 0.0% | 7.7 次/帧 |
//!   | 8 MB（≈ 旧「8 块」）| 54.2% | 3.5 次/帧 |
//!   | 16 MB | 86.3% | ~1 次/帧 |
//!   | **96 MB（新默认）** | **89.2%** | **0 次/帧**（33 次落空全在头 12 帧）|
//!
//!   顺带修掉**我自己引入的一个记账 bug**：`take` 时没把 `bytes` 减掉 ⇒
//!   "取出去再还回来"重复计数，跑一阵子后 `give` 全被拒、池静默失效。
//!   新单测 `pool_accounting_survives_repeated_take_and_give` 钉住（200 轮取还）。
//! * **整帧（两刀合计）**：一个**噪声很小**的窗口里做 8 轮换序交替 ——
//!   旧 min 49.07 / median 51.05、**新 min 47.28 / median 49.79**
//!   ⇒ **−2.5%（中位）/ −3.6%（min）**；同窗 dav1d 单线程 **11.60 ms**。
//!   ⚠️ 换个窗口噪声就能到 ±40%（同一对二进制 `PHASE` 总和从 44.8 漂到 90.6），
//!   **所以只认这一组"两版都稳定"的数据**。
//!
//! **验收**：真素材 20 帧与改前**逐字节相同**（21 个 nv12 全 `cmp`）、与 dav1d
//! **逐像素一致**；`ME_NO_SIMD` 开/关逐字节；row-mt 默认/顺序/并行三路逐字节；
//! 13 条受控流全 0 差；**workspace 882 项 0 failed**（`me-decode` lib 387 项）。
//!
//! **一条方法论（本轮最该记住的）**：**这台机器上 ±5% 以下的改动不可测**。
//! 两种可靠手段：① **同进程交替的内核微基准**（`bench_*`，`#[ignore]` 手工跑）；
//! ② **确定性计数**（命中率、访存次数、指令条数）—— 它们不受机器负载影响。
//! 墙钟 `elapsedMs` / `PHASE` 只在"两版都稳定"的窗口里才能用。
//!
//! **一处订正**（第二十六轮写错了）：那句"`cdef_direction` 每 64×64 只调一次"**不对** ——
//! `cdef_block` 是按 **8×8** 调的（`step4 = NUM_4X4_BLOCKS_WIDE[BLOCK_8X8] = 2`），
//! 所以方向搜索确实**每 8×8 块一次**（1080p ≈ 3.24 万次/帧）。那句话想说的其实是
//! "三个平面共用一次方向搜索"。它仍是候选（约占 CDEF 的 1/5），但没原来暗示的那么廉价。
//!
//! **下一步（按采样占比重排）**：`deblock_edge4` **5.4%**（i32 通道、一次只滤 **4 条线**
//! —— 与本轮 CDEF 同一类问题；但要改 8/16 线**得同时让 `run_line` 一次走 8 行**，
