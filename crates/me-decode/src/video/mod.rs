//! #### 第四十一轮（2026-10-06）：CDEF 整帧 memcpy —— **设计被逐字节验证、性能却 +14.2%** 的否定实验
//!
//! **实测 +14.2%（0/28 轮更快）**，67.06 → 76.64 ms/帧（**+9.58 ms/帧**），**已完整回退**。
//!
//! ### 起因与推理（**推理本身是对的**）
//!
//! 采样里内存原语的最大单一来源就是 `cdef::apply` 一上来那次
//! `let mut cdef = frame.clone();`（1080p 一帧 **6.2 MB**，单占整帧 1.3%）。
//! 而 CDEF 会把**可见区每一个样本**都写进 `CdefFrame` —— 要么由 `cdef_filter`
//! 滤波写，要么在 `cdef_block` 的**两个早退分支**（`idx < 0` / 四个 4×4 全 skip）
//! 里原样搬 ⇒ 可见区**不必先拷**；只有 **padding** 必须逐字节相同（那里有
//! "帧右/下边界超块伸出区"重建出来的像素，会被超分上采样读到）。
//!
//! 改法：`CurrFrame::new` + 新增 `Plane::copy_padding_from`（只拷 padding），
//! 两个早退分支改成逐块搬（新增 `cdef::copy_block`）。
//! ⭐ **改完 24 帧 `diff -r` 逐字节相同**，单测 `copy_padding_from_touches_only_padding`
//! 也过 —— **覆盖率那条推理是对的**。
//!
//! ### 但性能崩了，根因量化对得上
//!
//! CDEF 的 scan 是**逐 8×8 块**走的，而 `skip` 块在真素材里占比很高：
//!
//! ```text
//!   16000 个 skip 块/帧 × 3 个平面 × 最多 8 行  ≈ 38 万次 set_row/帧
//!   每次只搬 16~128 字节、每样本一次 clamp ⇒ ~20~40 周期/次
//!   ⇒ 8~15 M 周期 ≈ 5~10 ms/帧         （实测 +9.58 ms）
//! ```
//!
//! 对照：那 6.2 MB 的 memcpy 在 ~7 GB/s 下只要 **0.9 ms/帧**。
//!
//! ⭐ **教训：「少做事」要看粒度。** 总量少 ≠ 更快 —— 这台机器上"一次 6.2 MB 的
//! memcpy"**比**"只拷不滤波的那 60%、但按 8 样本一段拷"更便宜。要赢必须把拷贝
//! **聚成长串**（重排 `apply` 的扫描），而那样上限也只有 1.3% ⇒ 不值得。
//! **与第三十九刀（去块 8 线）同源：先问"省下来的是哪一档粒度"。**
//!
//! ⚠️ **方法论补丁**：**逐字节相同 / `ME_NO_SIMD` 这类判据只能证明"没算错"，
//! 证明不了"没变慢"。** 凡是以"结构上必然更少"为由的改动，**仍然必须先实测**。
//!
//! ⚠️ 顺手核对过：`[profile.release]` **没有**开 `debug-assertions`
//! （只有 `[profile.test]` 开）⇒ 热路径上的 `debug_assert!` 在发布版不花钱。
//!
//! ### 本轮同时留下的一份"确定版"全局账（分母修正）
//!
//! ⚠️ **采样总量是 22387**（主线程 11130 + 另一个线程 11257，后者几乎整段停在
